import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { transformSync } from "@swc/core";

const root = new URL("../", import.meta.url);
const esm = new URL("esm/", root);
const cjs = new URL("cjs/", root);
const header = "// Generated by scripts/build.js. Do not edit.\n";
const helpers = (await readdir(esm))
  .filter((name) => name.endsWith(".js") && name !== "index.js")
  .sort();
const exports = helpers.map((file) => {
  const name = file.slice(0, -3);
  if (!/^_[a-z][a-z0-9_]*$/.test(name)) {
    throw new Error(`Invalid helper module name: ${file}`);
  }
  return `export { _ as ${name} } from "./${file}";\n`;
});
const stub = exports.join("");
await writeFile(new URL("index.js", esm), header + stub);

await rm(cjs, { recursive: true, force: true });
await mkdir(cjs, { recursive: true });
await writeFile(new URL("package.json", cjs), '{"type":"commonjs"}\n');
for (const name of [...helpers, "index.js"]) {
  const source = name === "index.js" ? stub : await readFile(new URL(name, esm), "utf8");
  const { code } = transformSync(source, {
    filename: name,
    swcrc: false,
    configFile: false,
    jsc: { parser: { syntax: "ecmascript" }, target: "esnext" },
    module: { type: "commonjs", strict: true, noInterop: true },
  });
  await writeFile(new URL(name, cjs), header + code);
}
