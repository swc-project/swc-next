use std::{collections::BTreeSet, fmt::Write};

use super::field_name;
use crate::{
    output::RawOutput,
    schema::{AstType, Schema},
};

pub(super) fn protocol(schema: &Schema) -> RawOutput {
    let nodes = schema
        .types
        .iter()
        .filter_map(|ty| match ty {
            AstType::Struct(ast) => Some(ast),
            _ => None,
        })
        .collect::<Vec<_>>();
    let fields = nodes
        .iter()
        .flat_map(|ast| ast.fields.iter().map(|field| field_name(&field.name)))
        .collect::<BTreeSet<_>>();
    let mut output = String::from(
        "// Generated by ast_tools. Do not edit.\nimport type { AstMeta } from '#protocol/types';\n",
    );
    // ID zero has no native slot; name-based entry points use it for unknown fields.
    writeln!(
        output,
        "export const FIELD_COUNT = {};\nexport const Field = Object.freeze({{",
        fields.len() + 1
    )
    .unwrap();
    for (index, name) in fields.iter().enumerate() {
        writeln!(output, "  {name}: {},", index + 1).unwrap();
    }
    output.push_str(
        r#"} as const);
const fields: Readonly<Record<string, number>> = Field;
export function fieldId(name: string): number {
  const id = fields[name];
  return typeof id === 'number' ? id : 0;
}
export const fieldNames = ['', ...Object.keys(Field)];
export const initialFields: readonly (readonly number[])[] = [
"#,
    );
    for ast in nodes {
        let fields = ast
            .fields
            .iter()
            .filter_map(|field| {
                let (ty, optional) = match &schema.types[field.type_id] {
                    AstType::Option(option) => (&schema.types[option.inner_type_id], true),
                    ty => (ty, false),
                };
                let initialize = match ty {
                    AstType::Struct(_) | AstType::Enum(_) => true,
                    AstType::Primitive(primitive) if optional => {
                        matches!(primitive.name, "AstUtf8" | "AstWtf8")
                            || schema
                                .scalar_enums
                                .iter()
                                .any(|enumeration| enumeration.name == primitive.name)
                    }
                    _ => false,
                };
                initialize.then(|| format!("Field.{}", field_name(&field.name)))
            })
            .collect::<Vec<_>>();
        writeln!(output, "  [{}], // {}", fields.join(", "), ast.name).unwrap();
    }
    output.push_str("];\n// Public parser option values, in binary metadata order.\n");
    for (name, ty) in [("languages", "Lang"), ("sourceTypes", "SourceType")] {
        let options = schema
            .scalar_enums
            .iter()
            .find(|enumeration| enumeration.name == ty)
            .unwrap();
        let names = options
            .variants
            .iter()
            .map(|variant| variant.name.to_ascii_lowercase())
            .collect::<Vec<_>>();
        writeln!(output, "export const {name} = {names:?} as const;").unwrap();
    }
    output.push_str("export const parserMeta: readonly AstMeta[] = languages.flatMap(lang =>\n  sourceTypes.map(sourceType => Object.freeze({ lang, sourceType })));\n");
    RawOutput {
        path: "npm/core-ffi2/src-js/protocol/protocol.ts".into(),
        content: output.into_bytes(),
    }
}
