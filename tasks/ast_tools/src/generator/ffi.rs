//! Shared physical field layout and child enumeration for the buffer-backed AST API.
use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write,
};

use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use crate::{
    output::{RawOutput, RustOutput},
    schema::{AstType, FieldLocation, Schema, TypeId},
};

use super::ast_node::concrete_node_kinds;
use super::estree::{ENUMS, estree_field_name, estree_type};
use super::ffi_protocol::{field_rule, keys};

pub fn ffi(schema: &Schema) -> Vec<RawOutput> {
    let mut metadata = String::from(
        "import type { NodeLayout, EnumValue } from \"./types.ts\";\nimport type { Lang, SourceType } from \"@swc-next/types\";\nexport const layouts: readonly NodeLayout[] = Object.freeze<NodeLayout[]>([\n",
    );
    let mut kinds = String::from("export const NodeKind = Object.freeze({\n");
    let mut declarations = String::from(
        "// Generated by tasks/ast_tools. Do not edit.\nexport declare const NodeKind: {\n",
    );
    let mut fast_fields: BTreeMap<String, Vec<(usize, String)>> = BTreeMap::new();
    let mut extra_counts = Vec::new();
    let mut validator_arms = TokenStream::new();
    let mut count = 0usize;
    for ast in schema.types.iter().filter_map(|ty| match ty {
        AstType::Struct(ast) => Some(ast),
        _ => None,
    }) {
        let kind = count;
        count += 1;
        writeln!(kinds, "  {}: {kind},", ast.name).unwrap();
        writeln!(declarations, "  readonly {}: {kind};", ast.name).unwrap();
        writeln!(
            metadata,
            "  {{ name: {:?}, type: {:?}, extra: {}, fields: {{",
            ast.name,
            estree_type(&ast.name),
            ast.layout
                .extra_start_offset()
                .map_or("null".into(), |n| n.to_string())
        )
        .unwrap();
        extra_counts.push(ast.layout.extra_count);
        let mut checks = TokenStream::new();
        if let Some(pointer) = ast.layout.extra_start_offset() {
            let count = ast.layout.extra_count;
            checks.extend(quote!(input.extra(#pointer, #count)?;));
        }
        for (index, field) in ast.fields.iter().enumerate() {
            let location = match ast.layout.fields[index] {
                FieldLocation::Payload { offset, .. } => quote!(Field::Payload(#offset)),
                FieldLocation::Extra { index } => quote!(Field::Extra(#index)),
            };
            checks.extend(validate_field(field.type_id, location.clone(), schema));
            if field.attrs.estree_skip {
                continue;
            }
            let name = estree_field_name(&ast.name, &field.name);
            let (extra, offset) = match ast.layout.fields[index] {
                FieldLocation::Payload { offset, .. } => (false, offset),
                FieldLocation::Extra { index } => (true, index),
            };
            writeln!(
                metadata,
                "    {name}: [{extra}, {offset}, {}],",
                descriptor(field.type_id, schema)
            )
            .unwrap();
            let physical = fast_field_expression(
                field.type_id,
                extra,
                offset,
                ast.layout.extra_start_offset(),
                &name,
                schema,
            );
            let expressions: Vec<_> = [false, true]
                .into_iter()
                .map(|ts| match field_rule(ast, &name, ts) {
                    "Native" => physical.clone(),
                    "List" | "Params" => Some(format!("ast.list(this.#id, {name:?})")),
                    "False" => Some("false".into()),
                    "True" => Some("true".into()),
                    "Null" => Some("null".into()),
                    _ => None,
                })
                .collect();
            if expressions.iter().any(Option::is_some) {
                let fallback = format!("ast.getField(this.#id, {name:?}, kind)");
                let js = expressions[0].as_ref().unwrap_or(&fallback);
                let ts = expressions[1].as_ref().unwrap_or(&fallback);
                let expression = if js == ts {
                    js.clone()
                } else {
                    format!("ast._isTs ? ({ts}) : ({js})")
                };
                fast_fields
                    .entry(name.clone())
                    .or_default()
                    .push((kind, expression));
            }
        }
        metadata.push_str("  } },\n");
        if !checks.is_empty() {
            let ty = format_ident!("{}", ast.name);
            validator_arms.extend(quote!(NodeKind::#ty => { #checks }));
        }
    }
    metadata.push_str("] );\n");
    kinds.push_str("} as const);\n");
    declarations.push_str("};\n");
    metadata.push_str(&kinds);
    writeln!(
        metadata,
        "export const nativeExtraCounts: readonly number[] = Object.freeze({extra_counts:?});"
    )
    .unwrap();
    metadata.push_str("export const enums: Readonly<Record<string, readonly EnumValue[]>> & { readonly Lang: readonly Lang[]; readonly SourceType: readonly SourceType[] } = Object.freeze({\n");
    for (name, values) in ENUMS {
        writeln!(
            metadata,
            "  {name}: Object.freeze([{}] as const),",
            values.join(", ")
        )
        .unwrap();
    }
    metadata.push_str("});\n");
    // Public getters mirror the projection key tables; native-only fields stay
    // reachable through `get`/`set` and `AstView.value`.
    let mut names = BTreeSet::new();
    for ast in schema.types.iter().filter_map(|ty| match ty {
        AstType::Struct(ast) => Some(ast),
        _ => None,
    }) {
        for ts in [false, true] {
            names.extend(keys(ast, ts));
        }
    }
    let numeric_kind = fast_fields["value"]
        .iter()
        .find(|(_, expression)| expression.contains("getFloat64"))
        .unwrap()
        .0;
    let mut node_js = String::from(
        r#"// Generated by tasks/ast_tools. Do not edit.
import { staticTypes as typeNames } from './protocol.ts';
import type { AstView } from './index.ts';
import type { NodeField, FieldInput } from './types.ts';
export class NodeView {
  // Retain a buffer-free shape across batches that release every AST.
  static #shape = new this(null!, 0);
  #ast: AstView;
  #id: number;
  constructor(ast: AstView, id: number) {
    this.#ast = ast;
    this.#id = id;
  }
  static isSame(left: unknown, right: unknown): boolean {
    return left === right || (left instanceof NodeView && right instanceof NodeView && left.#ast === right.#ast && left.#id === right.#id);
  }
  get ast(): AstView { return this.#ast; }
  get nodeId(): number { return this.#id; }
  get<K extends string>(field: K): NodeField<K> { return this.#ast.value(this.#id, field, undefined, true) as NodeField<K>; }
  set<K extends string>(field: K, value: FieldInput<K>): void { this.#ast.writeNativeField(this.#id, field, value); }
  toJSON(): unknown { return this.#ast.materialize(this); }
"#,
    );
    writeln!(node_js, "  _numberValue(): NodeField<\"value\"> {{\n    const ast = this.#ast;\n    const kind = ast._kindAt(this.#id);\n    if (kind !== {numeric_kind}) {{ return ast.getField(this.#id, \"value\", kind); }}\n    const row = ast.row(this.#id);\n    return (row === -1 ? ast._view : ast._arena!.view!).getFloat64(ast._payloadAt(this.#id, row), true);\n  }}\n  _setNumberValue(value: FieldInput<\"value\">) {{ this.#ast.setField(this.#id, \"value\", value); }}").unwrap();
    for name in names {
        writeln!(node_js, "  get {name}(): NodeField<{name:?}> {{").unwrap();
        if name == "type" {
            node_js.push_str("    const ast = this.#ast;\n    const kind = this.#id < ast.nodeCount ? ast._bytes[ast._kinds + this.#id] : ast.kind(this.#id);\n    const type = typeNames[kind];\n    return type == null ? ast.getField(this.#id, \"type\") : type as NodeField<\"type\">;\n");
        } else {
            node_js
                .push_str("    const ast = this.#ast;\n    const kind = ast._kindAt(this.#id);\n");
            if fast_fields.contains_key(&name) {
                let mut groups: BTreeMap<&str, Vec<usize>> = BTreeMap::new();
                for (kind, expression) in &fast_fields[&name] {
                    groups.entry(expression).or_default().push(*kind);
                }
                // Share physical loads when every direct branch needs them.
                // Keeping one copy also lets V8 inline these getters into callers.
                let shared_location = groups.len() > 1
                    && groups.keys().all(|expression| {
                        expression.contains("offset") || expression.contains("view")
                    });
                if shared_location {
                    node_js.push_str("    const row = ast.row(this.#id);\n    const offset = ast._payloadAt(this.#id, row);\n    const view = row === -1 ? ast._view : ast._arena!.view!;\n");
                }
                node_js.push_str("    switch (kind) {\n");
                for (expression, kinds) in groups {
                    for kind in kinds {
                        writeln!(node_js, "      case {kind}:").unwrap();
                    }
                    let physical = !shared_location
                        && (expression.contains("offset") || expression.contains("view"));
                    if physical {
                        node_js.push_str("      {\n        const row = ast.row(this.#id);\n        const offset = ast._payloadAt(this.#id, row);\n        const view = row === -1 ? ast._view : ast._arena!.view!;\n");
                    }
                    writeln!(
                        node_js,
                        "        return ({expression}) as NodeField<{name:?}>;"
                    )
                    .unwrap();
                    if physical {
                        node_js.push_str("      }\n");
                    }
                }
                writeln!(
                    node_js,
                    "      default: return ast.getField(this.#id, {name:?}, kind);\n    }}"
                )
                .unwrap();
            } else {
                writeln!(
                    node_js,
                    "    return ast.getField(this.#id, {name:?}, kind);"
                )
                .unwrap();
            }
        }
        writeln!(
            node_js,
            "  }}\n  set {name}(value: FieldInput<{name:?}>) {{ this.#ast.setField(this.#id, {name:?}, value); }}"
        )
        .unwrap();
    }
    node_js.push_str("}\n");
    writeln!(node_js, "class NumericNodeView extends NodeView {{\n  constructor(ast: AstView, id: number) {{ super(ast, id); }}\n  static #shape = new this(null!, 0);\n  get value(): NodeField<\"value\"> {{ return this._numberValue(); }}\n  set value(value: FieldInput<\"value\">) {{ this._setNumberValue(value); }}\n}}\nexport function createNodeView(ast: AstView, id: number, kind: number): NodeView {{\n  return kind === {numeric_kind} ? new NumericNodeView(ast, id) : new NodeView(ast, id);\n}}").unwrap();
    metadata.insert_str(0, "// Generated by tasks/ast_tools. Do not edit.\n");
    metadata.push_str("for (const layout of layouts) {\n  for (const field of Object.values(layout.fields)) { Object.freeze(field); }\n  Object.freeze(layout.fields); Object.freeze(layout);\n}\n");
    let rust = RustOutput {
        path: "crates/swc_ecma_ast/src/ffi/schema.rs".into(),
        tokens: quote! {
            //! Generated by tasks/ast_tools. Do not edit.
            use crate::*;
            pub(super) const NODE_KIND_COUNT: usize = #count;
            pub(super) enum Field { Payload(usize), Extra(usize) }
            pub(super) trait FieldValidator {
                fn extra(&mut self, pointer: usize, count: usize) -> Result<(), super::DeserializeError>;
                fn node(&mut self, field: Field, kinds: &[NodeKind], optional: bool) -> Result<(), super::DeserializeError>;
                fn list(&mut self, field: Field, kinds: &[NodeKind], optional: bool) -> Result<(), super::DeserializeError>;
                fn boolean(&mut self, field: Field) -> Result<(), super::DeserializeError>;
                fn enumeration(&mut self, field: Field, count: usize, optional: bool) -> Result<(), super::DeserializeError>;
                fn string(&mut self, field: Field, wtf8: bool, optional: bool) -> Result<(), super::DeserializeError>;
            }
            pub(super) fn validate_fields(kind: NodeKind, input: &mut impl FieldValidator) -> Result<(), super::DeserializeError> {
                match kind { #validator_arms _ => {} }
                Ok(())
            }
        },
    }.into();
    let mut outputs = vec![
        rust,
        RawOutput {
            path: "packages/ast/schema.ts".into(),
            content: metadata.into_bytes(),
        },
        RawOutput {
            path: "packages/ast/node-kinds.d.ts".into(),
            content: declarations.into_bytes(),
        },
        RawOutput {
            path: "packages/ast/node.ts".into(),
            content: node_js.into_bytes(),
        },
    ];
    outputs.push(super::ffi_protocol::protocol(schema));
    outputs
}

fn validate_field(id: TypeId, field: TokenStream, schema: &Schema) -> TokenStream {
    let mut optional = false;
    let mut ty = &schema.types[id];
    let mut inner_id = id;
    if let AstType::Option(value) = ty {
        optional = true;
        inner_id = value.inner_type_id;
        ty = &schema.types[inner_id];
    }
    let kinds = |id| {
        concrete_node_kinds(id, schema)
            .iter()
            .map(|name| {
                let name = format_ident!("{name}");
                quote!(NodeKind::#name)
            })
            .collect::<Vec<_>>()
    };
    match ty {
        AstType::Struct(_) | AstType::Enum(_) => {
            let kinds = kinds(inner_id);
            quote!(input.node(#field, &[#(#kinds),*], #optional)?;)
        }
        AstType::SubRange(range) => {
            let (id, optional) = match &schema.types[range.inner_type_id] {
                AstType::Option(value) => (value.inner_type_id, true),
                _ => (range.inner_type_id, false),
            };
            let kinds = kinds(id);
            quote!(input.list(#field, &[#(#kinds),*], #optional)?;)
        }
        AstType::Primitive(value) => match value.name {
            "bool" => quote!(input.boolean(#field)?;),
            "AstUtf8" | "AstWtf8" => {
                let wtf8 = value.name == "AstWtf8";
                quote!(input.string(#field, #wtf8, #optional)?;)
            }
            name => {
                if let Some(enumeration) =
                    schema.scalar_enums.iter().find(|value| value.name == name)
                {
                    let count = enumeration.variants.len();
                    quote!(input.enumeration(#field, #count, #optional)?;)
                } else {
                    TokenStream::new()
                }
            }
        },
        _ => unreachable!(),
    }
}

pub(super) fn descriptor(id: TypeId, schema: &Schema) -> String {
    let mut optional = false;
    let mut ty = &schema.types[id];
    if let AstType::Option(option) = ty {
        optional = true;
        ty = &schema.types[option.inner_type_id];
    }
    let name = match ty {
        AstType::Struct(_) | AstType::Enum(_) => "node".into(),
        AstType::SubRange(range) => {
            optional = matches!(&schema.types[range.inner_type_id], AstType::Option(_));
            assert!(matches!(
                &schema.types[range.inner_type_id],
                AstType::Struct(_) | AstType::Enum(_) | AstType::Option(_)
            ));
            "list".into()
        }
        AstType::Primitive(primitive) => match primitive.name {
            "AstUtf8" | "AstWtf8" => "string".into(),
            name if ENUMS.iter().any(|(enum_name, _)| *enum_name == name) => format!("enum:{name}"),
            name => name.to_string(),
        },
        _ => unreachable!(),
    };
    format!("{name:?}, {optional}")
}

fn fast_field_expression(
    id: TypeId,
    extra: bool,
    offset: usize,
    pointer: Option<usize>,
    name: &str,
    schema: &Schema,
) -> Option<String> {
    let descriptor = descriptor(id, schema);
    let (encoding, tail) = descriptor.split_once(", ").unwrap();
    let optional = tail.split(',').next().unwrap();
    let encoding = encoding.trim_matches('"');
    if encoding == "list" {
        return Some(format!("ast.list(this.#id, {name:?})"));
    }
    let address = if extra {
        let words = if matches!(encoding, "string" | "f64") {
            ", 2"
        } else {
            ""
        };
        format!(
            "ast.extraOffset(offset, {}, {offset}{words})",
            pointer.unwrap()
        )
    } else {
        format!("offset + {offset}")
    };
    let expression = match encoding {
        "bool" => format!("view.getUint8({address}) !== 0"),
        "u8" => format!("view.getUint8({address})"),
        "i8" => format!("view.getInt8({address})"),
        "u16" => format!("view.getUint16({address}, true)"),
        "i16" => format!("view.getInt16({address}, true)"),
        "u32" => format!("view.getUint32({address}, true)"),
        "i32" => format!("view.getInt32({address}, true)"),
        "f64" => format!("view.getFloat64({address}, true)"),
        "node" => format!("ast._nodeAt(ast.childAt(this.#id, {address}, {optional}, view))"),
        "list" => format!("ast.list(this.#id, {name:?})"),
        "string" => format!("ast.stringAt({address}, {optional}, view)"),
        value if value.starts_with("enum:") => {
            format!("ast.enumAt({address}, {:?}, {optional}, view)", &value[5..])
        }
        _ => return None,
    };
    Some(if extra {
        format!(
            "this.#id >= ast.nodeCount || view.getUint32(offset + {}, true) >= ast._extraCount ? ast.getField(this.#id, {name:?}, kind) : {expression}",
            pointer.unwrap()
        )
    } else {
        expression
    })
}
