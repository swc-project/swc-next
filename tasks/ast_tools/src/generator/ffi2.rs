//! Shared physical field layout and child enumeration for the buffer-backed AST API.
use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write,
};

use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use crate::{
    output::{RawOutput, RustOutput},
    schema::{AstType, FieldLocation, Schema, TypeId},
};

use super::ast_node::concrete_node_kinds;
use super::estree::{ENUMS, estree_field_name, estree_type, is_ts_field, ts_extra_fields};

pub fn ffi2(schema: &Schema) -> Vec<RawOutput> {
    let mut metadata = String::from("export const layouts = Object.freeze([\n");
    let mut kinds = String::from("export const NodeKind = Object.freeze({\n");
    let mut declarations = String::from(
        "// Generated by tasks/ast_tools. Do not edit.\nexport declare const SCHEMA_ID: number;\nexport declare const NodeKind: {\n",
    );
    let mut names = BTreeSet::new();
    let mut fast_fields: BTreeMap<String, Vec<(usize, String)>> = BTreeMap::new();
    let mut references_js =
        String::from("// Generated by tasks/ast_tools. Do not edit.\nconst NONE = 0xffffffff;\n\n");
    let mut reference_reader_groups: BTreeMap<String, usize> = BTreeMap::new();
    let mut reference_reader_kinds = Vec::new();
    let native_kinds: BTreeMap<_, _> = schema
        .types
        .iter()
        .filter_map(|ty| match ty {
            AstType::Struct(ast) => Some(ast.name.as_str()),
            _ => None,
        })
        .enumerate()
        .map(|(index, name)| (name, index))
        .collect();
    let mut extra_counts = Vec::new();
    let mut writable_tables = Vec::new();
    let mut child_kind_tables = Vec::new();
    let mut validator_arms = TokenStream::new();
    let mut count = 0usize;
    for ast in schema.types.iter().filter_map(|ty| match ty {
        AstType::Struct(ast) => Some(ast),
        _ => None,
    }) {
        let kind = count;
        count += 1;
        writeln!(kinds, "  {}: {kind},", ast.name).unwrap();
        writeln!(declarations, "  readonly {}: {kind};", ast.name).unwrap();
        writeln!(
            metadata,
            "  {{ name: {:?}, type: {:?}, extra: {}, fields: {{",
            ast.name,
            estree_type(&ast.name),
            ast.layout
                .extra_start_offset()
                .map_or("null".into(), |n| n.to_string())
        )
        .unwrap();
        let mut projected = vec![];
        let mut ts_fields = vec![];
        let mut child_fields = Vec::new();
        let mut reference_fields = Vec::new();
        let mut writable = Vec::new();
        let mut child_kinds = Vec::new();
        extra_counts.push(ast.layout.extra_count);
        let mut checks = TokenStream::new();
        if let Some(pointer) = ast.layout.extra_start_offset() {
            let count = ast.layout.extra_count;
            checks.extend(quote!(input.extra(#pointer, #count)?;));
        }
        for (index, field) in ast.fields.iter().enumerate() {
            let location = match ast.layout.fields[index] {
                FieldLocation::Payload { offset, .. } => quote!(Field::Payload(#offset)),
                FieldLocation::Extra { index } => quote!(Field::Extra(#index)),
            };
            checks.extend(validate_field(field.type_id, location.clone(), schema));
            let child_type = if let AstType::SubRange(range) = &schema.types[field.type_id] {
                child_reference(range.inner_type_id, quote!(value), schema).map(|_| "list")
            } else {
                child_reference(field.type_id, quote!(value), schema).map(|_| "node")
            };
            if let Some(child_type) = child_type {
                let (extra, offset) = match ast.layout.fields[index] {
                    FieldLocation::Payload { offset, .. } => (false, offset),
                    FieldLocation::Extra { index } => (true, index),
                };
                child_fields.push(format!("[{extra}, {offset}, {child_type:?}]"));
                reference_fields.push((extra, offset, child_type == "list"));
            }
            if field.attrs.estree_skip {
                continue;
            }
            let name = estree_field_name(&ast.name, &field.name);
            let (extra, offset) = match ast.layout.fields[index] {
                FieldLocation::Payload { offset, .. } => (false, offset),
                FieldLocation::Extra { index } => (true, index),
            };
            writeln!(
                metadata,
                "    {name}: [{extra}, {offset}, {}],",
                descriptor(field.type_id, schema)
            )
            .unwrap();
            projected.push(name.clone());
            if is_ts_field(&ast.name, &name) {
                ts_fields.push(name.clone());
            }
            if direct_field(&ast.name, &name) {
                writable.push(format!("{name}: true"));
                if let Some(mut expression) = fast_field_expression(
                    field.type_id,
                    extra,
                    offset,
                    ast.layout.extra_start_offset(),
                    &name,
                    schema,
                ) {
                    if is_ts_field(&ast.name, &name) {
                        expression = format!("ast._isTs ? ({expression}) : undefined");
                    }
                    fast_fields
                        .entry(name.clone())
                        .or_default()
                        .push((kind, expression));
                }
            }
            if child_type.is_some() {
                let child = match &schema.types[field.type_id] {
                    AstType::SubRange(range) => range.inner_type_id,
                    _ => field.type_id,
                };
                let child = match &schema.types[child] {
                    AstType::Option(option) => option.inner_type_id,
                    _ => child,
                };
                let allowed: Vec<_> = concrete_node_kinds(child, schema)
                    .iter()
                    .map(|name| native_kinds[name.as_str()])
                    .collect();
                child_kinds.push(format!("{name}: {allowed:?}"));
            }
            names.insert(name);
        }
        let extras = ts_extra_fields(&ast.name);
        for (name, _) in extras {
            names.insert((*name).into());
        }
        writeln!(
            metadata,
            "  }}, children: [{}], keys: {projected:?}, ts: {ts_fields:?}, extras: {{",
            child_fields.join(", ")
        )
        .unwrap();
        for (name, value) in extras {
            writeln!(metadata, "    {name}: {value},").unwrap();
        }
        metadata.push_str("  } },\n");
        writable_tables.push(format!("{{ {} }}", writable.join(", ")));
        child_kind_tables.push(format!("{{ {} }}", child_kinds.join(", ")));
        let body = reference_reader_body(&reference_fields, ast.layout.extra_start_offset());
        let reader = if let Some(reader) = reference_reader_groups.get(&body) {
            *reader
        } else {
            let reader = reference_reader_groups.len();
            writeln!(
                references_js,
                "function readReferences{reader}(ast, payload, output) {{\n{body}}}\n"
            )
            .unwrap();
            reference_reader_groups.insert(body, reader);
            reader
        };
        reference_reader_kinds.push(reader);
        if !checks.is_empty() {
            let ty = format_ident!("{}", ast.name);
            validator_arms.extend(quote!(NodeKind::#ty => { #checks }));
        }
    }
    references_js.push_str("export const referenceReaders = [\n");
    for reader in reference_reader_kinds {
        writeln!(references_js, "  readReferences{reader},").unwrap();
    }
    references_js.push_str("];\n");
    writeln!(
        references_js,
        "export const nativeExtraCounts = {extra_counts:?};"
    )
    .unwrap();
    writeln!(
        references_js,
        "export const nativeWritableFields = [\n{}\n];",
        writable_tables.join(",\n")
    )
    .unwrap();
    writeln!(
        references_js,
        "export const nativeFieldKinds = [\n{}\n];",
        child_kind_tables.join(",\n")
    )
    .unwrap();
    metadata.push_str("] );\n");
    kinds.push_str("});\n");
    declarations.push_str("};\n");
    metadata.push_str(&kinds);
    metadata.push_str("export const enums = Object.freeze({\n");
    for (name, values) in ENUMS {
        writeln!(
            metadata,
            "  {name}: Object.freeze([{}]),",
            values.join(", ")
        )
        .unwrap();
    }
    metadata.push_str("});\n");
    names.extend(
        [
            "type",
            "start",
            "end",
            "raw",
            "value",
            "bigint",
            "regex",
            "prefix",
            "left",
            "right",
            "argument",
            "params",
            "expression",
            "declare",
            "global",
            "optional",
            "typeAnnotation",
            "decorators",
            "sourceType",
            "body",
        ]
        .map(String::from),
    );
    let mut node_js = String::from(
        "// Generated by tasks/ast_tools. Do not edit.\nimport { staticTypes } from './projection.js';\n// Keep the private lookup in V8's fast packed-elements representation.\nconst typeNames = Array.from(staticTypes);\nexport class NodeView {\n  // Keep the view shape alive across batches that release every AST.\n  // This template contains no AST or buffer and never serves a node read.\n  static #shape = new this(null, 0, 0, 0);\n  static isSame(left, right) {\n    return left === right || (left instanceof NodeView && right instanceof NodeView && left.#ast === right.#ast && left.#id === right.#id);\n  }\n  #ast;\n  #id;\n  #kind;\n  #type;\n  #offset;\n  constructor(ast, id, kind = ast.kind(id), offset = ast.offset(id)) {\n    this.#ast = ast;\n    this.#id = id;\n    this.#kind = kind;\n    this.#type = typeNames[kind];\n    this.#offset = offset;\n  }\n  get ast() { return this.#ast; }\n  get nodeId() { return this.#id; }\n  get parent() { return this.#ast.parentNode(this.#id); }\n  toJSON() { return this.#ast.materialize(this); }\n  _numberValue() {\n    const ast = this.#ast;\n    if (ast._arena?.has(this.#id)) return ast.getField(this.#id, \"value\");\n    if (ast._edits === null) return ast._view.getFloat64(this.#offset, true);\n    const fields = ast._edits.get(this.#id);\n    if (fields?.has(\"value\")) return fields.get(\"value\");\n    return ast._view.getFloat64(this.#offset, true);\n  }\n  _setNumberValue(value) { this.#ast.setField(this.#id, \"value\", value); }\n",
    );
    for name in names {
        writeln!(node_js, "  get {name}() {{").unwrap();
        if name == "type" {
            node_js.push_str("    const ast = this.#ast;\n    if (ast._kindsChanged === false && ast._edits === null && this.#type !== null) return this.#type;\n    return ast.getField(this.#id, \"type\", this.#kind);\n");
        } else {
            writeln!(node_js, "    if (this.#ast._arena?.has(this.#id)) return this.#ast.getField(this.#id, {name:?});").unwrap();
            if fast_fields.contains_key(&name) {
                node_js.push_str("    const ast = this.#ast;\n    const kind = this.#kind;\n    const offset = this.#offset;\n    const view = ast._view;\n");
                writeln!(node_js, "    const fields = ast._edits?.get(this.#id);\n    if (fields?.has({name:?})) return fields.get({name:?});").unwrap();
                node_js.push_str("    switch (kind) {\n");
                let mut groups: BTreeMap<&str, Vec<usize>> = BTreeMap::new();
                for (kind, expression) in &fast_fields[&name] {
                    groups.entry(expression).or_default().push(*kind);
                }
                for (expression, kinds) in groups {
                    for kind in kinds {
                        writeln!(node_js, "      case {kind}:").unwrap();
                    }
                    writeln!(node_js, "        return {expression};").unwrap();
                }
                writeln!(
                    node_js,
                    "      default: return this.#ast.getField(this.#id, {name:?}, this.#kind);\n    }}"
                )
                .unwrap();
            } else {
                writeln!(
                    node_js,
                    "    return this.#ast.getField(this.#id, {name:?}, this.#kind);"
                )
                .unwrap();
            }
        }
        writeln!(
            node_js,
            "  }}\n  set {name}(value) {{ this.#ast.setField(this.#id, {name:?}, value); }}"
        )
        .unwrap();
    }
    node_js.push_str("}\n");
    let numeric_kind = fast_fields["value"]
        .iter()
        .find(|(_, expression)| expression.contains("getFloat64"))
        .unwrap()
        .0;
    writeln!(node_js, "class NumericNodeView extends NodeView {{\n  static #shape = new this(null, 0, {numeric_kind}, 0);\n  get value() {{ return this._numberValue(); }}\n  set value(value) {{ this._setNumberValue(value); }}\n}}\nexport function createNodeView(ast, id, kind, offset) {{\n  return kind === {numeric_kind} ? new NumericNodeView(ast, id, kind, offset) : new NodeView(ast, id, kind, offset);\n}}").unwrap();
    // Stable layout fingerprint; never use std's randomized/platform-dependent hashers for a wire format.
    let mut fingerprint = 2166136261u32;
    for byte in metadata.bytes() {
        fingerprint = (fingerprint ^ u32::from(byte)).wrapping_mul(16777619);
    }
    metadata.insert_str(0, &format!("// Generated by tasks/ast_tools. Do not edit.\nexport const SCHEMA_ID = {fingerprint};\n"));
    metadata.push_str("for (const layout of layouts) {\n  for (const field of Object.values(layout.fields)) Object.freeze(field);\n  for (const value of Object.values(layout.extras)) if (Array.isArray(value)) Object.freeze(value);\n  for (const child of layout.children) Object.freeze(child); Object.freeze(layout.children);\n  Object.freeze(layout.fields); Object.freeze(layout.keys); Object.freeze(layout.ts); Object.freeze(layout.extras); Object.freeze(layout);\n}\n");
    let rust = RustOutput {
        path: "crates/swc_ecma_ast/src/ffi2/schema.rs".into(),
        tokens: quote! {
            //! Generated by tasks/ast_tools. Do not edit.
            use crate::*;
            pub(super) const SCHEMA_ID: u32 = #fingerprint;
            pub(super) const NODE_KIND_COUNT: usize = #count;
            pub(super) enum Field { Payload(usize), Extra(usize) }
            pub(super) trait FieldValidator {
                fn extra(&mut self, pointer: usize, count: usize) -> Result<(), super::DeserializeError>;
                fn node(&mut self, field: Field, kinds: &[NodeKind], optional: bool) -> Result<(), super::DeserializeError>;
                fn list(&mut self, field: Field, kinds: &[NodeKind], optional: bool) -> Result<(), super::DeserializeError>;
                fn boolean(&mut self, field: Field) -> Result<(), super::DeserializeError>;
                fn enumeration(&mut self, field: Field, count: usize, optional: bool) -> Result<(), super::DeserializeError>;
                fn string(&mut self, field: Field, wtf8: bool, optional: bool) -> Result<(), super::DeserializeError>;
                #[allow(dead_code)]
                fn index(&mut self, field: Field, nonzero: bool) -> Result<(), super::DeserializeError>;
            }
            pub(super) fn validate_fields(kind: NodeKind, input: &mut impl FieldValidator) -> Result<(), super::DeserializeError> {
                match kind { #validator_arms _ => {} }
                Ok(())
            }
        },
    }.into();
    let mut outputs = vec![
        rust,
        RawOutput {
            path: "packages/ast/schema.js".into(),
            content: metadata.into_bytes(),
        },
        RawOutput {
            path: "packages/ast/schema.d.ts".into(),
            content: declarations.into_bytes(),
        },
        RawOutput {
            path: "packages/ast/node.js".into(),
            content: node_js.into_bytes(),
        },
        RawOutput {
            path: "packages/ast/references.js".into(),
            content: references_js.into_bytes(),
        },
    ];
    outputs.extend(super::estree_encoder::ffi2_encoder(schema));
    outputs
}

fn reference_reader_body(fields: &[(bool, usize, bool)], extra_pointer: Option<usize>) -> String {
    if fields.is_empty() {
        return "  return 0;\n".into();
    }
    let mut body = String::from("  const view = ast._view;\n  let length = 0;\n");
    let mut loaded_extra = false;
    for &(extra, offset, is_list) in fields {
        // Earlier payload fields must be checked before reading the extra pointer.
        if extra && !loaded_extra {
            writeln!(
                body,
                "  const extraStart = view.getUint32(payload + {}, true);",
                extra_pointer.unwrap()
            )
            .unwrap();
            loaded_extra = true;
        }
        body.push_str("  {\n");
        if extra {
            writeln!(body, "    const extraIndex = extraStart + {offset};").unwrap();
            body.push_str("    if (extraIndex >= ast._extraCount) throw new RangeError('AST extra-data reference out of bounds');\n    const offset = ast._extra + extraIndex * 8;\n");
        } else {
            writeln!(body, "    const offset = payload + {offset};").unwrap();
        }
        if is_list {
            body.push_str("    const start = view.getUint32(offset, true);\n    const end = view.getUint32(offset + 4, true);\n    if (start > end || end > ast._extraCount) throw new RangeError('AST list out of bounds');\n    for (let index = start; index < end; index++) {\n      const slot = ast._extra + index * 8;\n      const child = view.getUint32(slot, true);\n      if (child !== NONE) {\n        output[length++] = slot;\n        output[length++] = child;\n      }\n    }\n");
        } else {
            body.push_str("    const child = view.getUint32(offset, true);\n    if (child !== NONE) {\n      output[length++] = offset;\n      output[length++] = child;\n    }\n");
        }
        body.push_str("  }\n");
    }
    body.push_str("  return length;\n");
    body
}

fn validate_field(id: TypeId, field: TokenStream, schema: &Schema) -> TokenStream {
    let mut optional = false;
    let mut ty = &schema.types[id];
    let mut inner_id = id;
    if let AstType::Option(value) = ty {
        optional = true;
        inner_id = value.inner_type_id;
        ty = &schema.types[inner_id];
    }
    let kinds = |id| {
        concrete_node_kinds(id, schema)
            .iter()
            .map(|name| {
                let name = format_ident!("{name}");
                quote!(NodeKind::#name)
            })
            .collect::<Vec<_>>()
    };
    match ty {
        AstType::Struct(_) | AstType::Enum(_) => {
            let kinds = kinds(inner_id);
            quote!(input.node(#field, &[#(#kinds),*], #optional)?;)
        }
        AstType::SubRange(range) => {
            let (id, optional) = match &schema.types[range.inner_type_id] {
                AstType::Option(value) => (value.inner_type_id, true),
                _ => (range.inner_type_id, false),
            };
            let kinds = kinds(id);
            quote!(input.list(#field, &[#(#kinds),*], #optional)?;)
        }
        AstType::Primitive(value) => match value.name {
            "bool" => quote!(input.boolean(#field)?;),
            "AstUtf8" | "AstWtf8" => {
                let wtf8 = value.name == "AstWtf8";
                quote!(input.string(#field, #wtf8, #optional)?;)
            }
            "ScopeId" if !optional => quote!(input.index(#field, true)?;),
            "SymbolId" | "ReferenceId" if !optional => quote!(input.index(#field, false)?;),
            name => {
                if let Some(enumeration) =
                    schema.scalar_enums.iter().find(|value| value.name == name)
                {
                    let count = enumeration.variants.len();
                    quote!(input.enumeration(#field, #count, #optional)?;)
                } else {
                    TokenStream::new()
                }
            }
        },
        _ => unreachable!(),
    }
}

fn child_reference(id: TypeId, value: TokenStream, schema: &Schema) -> Option<TokenStream> {
    match &schema.types[id] {
        AstType::Struct(_) | AstType::Enum(_) => Some(quote!(Some((#value).node_id()))),
        AstType::Option(option)
            if matches!(
                &schema.types[option.inner_type_id],
                AstType::Struct(_) | AstType::Enum(_)
            ) =>
        {
            Some(quote!((#value).map(|node| node.node_id())))
        }
        _ => None,
    }
}

fn descriptor(id: TypeId, schema: &Schema) -> String {
    let mut optional = false;
    let mut ty = &schema.types[id];
    if let AstType::Option(option) = ty {
        optional = true;
        ty = &schema.types[option.inner_type_id];
    }
    let name = match ty {
        AstType::Struct(_) | AstType::Enum(_) => "node".into(),
        AstType::SubRange(range) => {
            assert!(matches!(
                &schema.types[range.inner_type_id],
                AstType::Struct(_) | AstType::Enum(_) | AstType::Option(_)
            ));
            "list".into()
        }
        AstType::Primitive(primitive) => match primitive.name {
            "AstUtf8" | "AstWtf8" => "string".into(),
            "Span" => "span".into(),
            "ScopeId" | "SymbolId" | "ReferenceId" => "ignored".into(),
            name if ENUMS.iter().any(|(enum_name, _)| *enum_name == name) => format!("enum:{name}"),
            name => name.to_string(),
        },
        _ => unreachable!(),
    };
    format!("{name:?}, {optional}")
}

// These nodes expose their physical fields directly. Ownership-adjusted patterns,
// directives, parameter wrappers and other projections use the shared fallback.
fn direct_field(kind: &str, field: &str) -> bool {
    match kind {
        "StringLiteral" => matches!(field, "value" | "raw"),
        "NumericLiteral" | "BooleanLiteral" => field == "value",
        "BindingIdentifier"
        | "IdentifierReference"
        | "IdentifierName"
        | "PrivateIdentifier"
        | "JsxIdentifier" => field == "name",
        "BinaryExpression"
        | "LogicalExpression"
        | "AssignmentExpression"
        | "MemberExpression"
        | "CallExpression"
        | "NewExpression"
        | "ExpressionStatement"
        | "ReturnStatement"
        | "AwaitExpression"
        | "ThrowStatement"
        | "IfStatement"
        | "ConditionalExpression"
        | "VariableDeclaration"
        | "JsxElement"
        | "JsxOpeningElement"
        | "JsxClosingElement"
        | "JsxFragment"
        | "JsxExpressionContainer"
        | "JsxSpreadChild"
        | "JsxSpreadAttribute"
        | "JsxAttribute"
        | "JsxMemberExpression"
        | "JsxNamespacedName"
        | "TemplateLiteral"
        | "ArrayExpression"
        | "ObjectExpression"
        | "BlockStatement" => true,
        _ => false,
    }
}

fn fast_field_expression(
    id: TypeId,
    extra: bool,
    offset: usize,
    pointer: Option<usize>,
    name: &str,
    schema: &Schema,
) -> Option<String> {
    let descriptor = descriptor(id, schema);
    let (encoding, optional) = descriptor.split_once(", ").unwrap();
    let encoding = encoding.trim_matches('"');
    let address = if extra {
        format!("ast.extraOffset(offset, {}, {offset})", pointer.unwrap())
    } else {
        format!("offset + {offset}")
    };
    Some(match encoding {
        "bool" => format!("view.getUint8({address}) !== 0"),
        "u8" => format!("view.getUint8({address})"),
        "i8" => format!("view.getInt8({address})"),
        "u16" => format!("view.getUint16({address}, true)"),
        "i16" => format!("view.getInt16({address}, true)"),
        "u32" => format!("view.getUint32({address}, true)"),
        "i32" => format!("view.getInt32({address}, true)"),
        "f64" => format!("view.getFloat64({address}, true)"),
        "node" => format!("ast.node(ast.childAt(this.#id, {address}, {optional}))"),
        "list" => format!("ast.listAt(this.#id, {address}, {name:?})"),
        "string" => format!("ast.stringAt({address}, {optional})"),
        value if value.starts_with("enum:") => {
            format!("ast.enumAt({address}, {:?}, {optional})", &value[5..])
        }
        _ => return None,
    })
}
