use std::fs;

use crate::{
    generator::js::js_field_name,
    output::RawOutput,
    schema::{AstStruct, AstStructField, AstType, Schema, TypeId},
    util::should_skip_field,
};

pub fn ast_decode(schema: &Schema) -> RawOutput {
    let node_kinds = read_node_kinds();
    let mut cases = String::new();

    for ty in schema.types.iter() {
        if let AstType::Struct(ast) = ty {
            cases.push_str(&generate_decode_for_struct(ast, schema));
        }
    }

    let node_kind_entries = node_kinds
        .iter()
        .enumerate()
        .map(|(index, name)| format!("  {name}: {index},"))
        .collect::<Vec<_>>()
        .join("\n");

    let content = format!(
        r#"// generated by tasks/ast_tools/src/generator/js/decode.rs, do not edit
const NONE = 0xffffffff;
const NODE_SIZE = 32;
const HEADER_SIZE = 12;
const NK = {{
{node_kind_entries}
}};
const IMPORT_PHASE = ["Evaluation", "Source", "Defer"];
const VAR_DECL_KIND = ["Var", "Let", "Const"];
const UNARY_OP = ["Minus", "Plus", "Bang", "Tilde", "TypeOf", "Void", "Delete"];
const UPDATE_OP = ["PlusPlus", "MinusMinus"];
const ASSIGN_OP = ["Assign", "AddAssign", "SubAssign", "MulAssign", "DivAssign", "ModAssign", "LShiftAssign", "RShiftAssign", "ZeroFillRShiftAssign", "BitOrAssign", "BitXorAssign", "BitAndAssign", "ExpAssign", "AndAssign", "OrAssign", "NullishAssign"];
const BINARY_OP = ["EqEq", "NotEq", "EqEqEq", "NotEqEq", "Lt", "LtEq", "Gt", "GtEq", "LShift", "RShift", "ZeroFillRShift", "Add", "Sub", "Mul", "Div", "Mod", "BitOr", "BitXor", "BitAnd", "LogicalOr", "LogicalAnd", "In", "InstanceOf", "Exp", "NullishCoalescing"];
const META_PROP_KIND = ["NewTarget", "ImportMeta"];
const METHOD_KIND = ["Method", "Getter", "Setter"];

export function decode(buffer, source) {{
  const u8 = buffer instanceof Uint8Array ? buffer : new Uint8Array(buffer);
  const dv = new DataView(u8.buffer, u8.byteOffset, u8.byteLength);
  const u32 = offset => dv.getUint32(offset, true);
  const nodeCount = u32(0);
  const extraCount = u32(4);
  const stringPoolSize = u32(8);
  const nodesOff = HEADER_SIZE;
  const extraOff = nodesOff + nodeCount * NODE_SIZE;
  const stringPoolOff = extraOff + extraCount * 4;
  const sourceLen = source.length;

  function stringAt(start, end) {{
    if (start === NONE) return null;
    if (start === end) return "";
    if (start < sourceLen) return source.slice(start, end);

    start -= sourceLen;
    end -= sourceLen;
    let out = "";
    for (let i = start; i < end; i++) {{
      out += String.fromCharCode(dv.getUint16(stringPoolOff + i * 2, true));
    }}
    return out;
  }}

  function extraAt(index) {{
    return u32(extraOff + index * 4);
  }}

  function nodeArray(start, len) {{
    const out = new Array(len);
    for (let i = 0; i < len; i++) out[i] = node(extraAt(start + i));
    return out;
  }}

  function optionalNodeArray(start, len) {{
    const out = new Array(len);
    for (let i = 0; i < len; i++) {{
      const id = extraAt(start + i);
      out[i] = id === NONE ? null : node(id);
    }}
    return out;
  }}

  function maybeNode(id) {{
    return id === NONE ? null : node(id);
  }}

  function node(id) {{
    if (id === NONE || id === 0) return null;
    const off = nodesOff + (id - 1) * NODE_SIZE;
    const tag = u8[off];
    const flags = dv.getUint16(off + 2, true);
    const start = u32(off + 4);
    const end = u32(off + 8);
    const f0 = u32(off + 12);
    const f1 = u32(off + 16);
    const f2 = u32(off + 20);
    const f3 = u32(off + 24);
    const f4 = u32(off + 28);
    switch (tag) {{
{cases}
      default:
        throw new Error(`Unknown node kind ${{tag}}`);
    }}
  }}

  return node(nodeCount);
}}

export default decode;
"#
    );

    RawOutput {
        path: "napi/parser/src-js/decode.js".to_string(),
        content: content.into_bytes(),
    }
}

fn generate_decode_for_struct(ast: &AstStruct, schema: &Schema) -> String {
    let mut field_index = 0usize;
    let mut flag_offset = 0usize;
    let mut props = Vec::new();

    for field in ast.fields.iter() {
        if should_skip_field(field, schema) {
            continue;
        }

        let field_name = js_field_name(&field.name);

        if is_span_type(field.type_id, schema) {
            props.push(format!("{field_name}: {{ start, end }}"));
            continue;
        }

        if let Some((expr, width)) = flag_decode_expr(field, flag_offset, schema) {
            props.push(format!("{field_name}: {expr}"));
            flag_offset += width;
            continue;
        }

        let Some(decoded) = decode_field(field, field_index, schema) else {
            unreachable!("{} has unsupported field {}", ast.name, field.name);
        };
        field_index += decoded.width;
        props.push(format!("{field_name}: {}", decoded.expr));
    }

    if field_index > 5 || flag_offset > u16::BITS as usize {
        unreachable!("{} cannot fit in PackedNode", ast.name);
    }

    let props = if props.is_empty() {
        format!("type: \"{}\"", ast.name)
    } else {
        format!("type: \"{}\", {}", ast.name, props.join(", "))
    };

    format!("      case NK.{}: return {{ {} }};\n", ast.name, props)
}

struct DecodedField {
    width: usize,
    expr: String,
}

fn decode_field(
    field: &AstStructField,
    field_index: usize,
    schema: &Schema,
) -> Option<DecodedField> {
    let slot = |offset| format!("f{}", field_index + offset);

    Some(match &schema.types[field.type_id] {
        AstType::Struct(_) | AstType::Enum(_) | AstType::Box(_) => DecodedField {
            width: 1,
            expr: format!("node({})", slot(0)),
        },
        AstType::Vec(ast) => DecodedField {
            width: 2,
            expr: if is_option_type(ast.inner_type_id, schema) {
                format!("optionalNodeArray({}, {})", slot(0), slot(1))
            } else {
                format!("nodeArray({}, {})", slot(0), slot(1))
            },
        },
        AstType::Option(ast) => decode_option_field(ast.inner_type_id, field_index, schema)?,
        AstType::Primitive(ast) => decode_primitive_field(ast.name, field_index)?,
    })
}

fn decode_option_field(
    inner_type_id: TypeId,
    field_index: usize,
    schema: &Schema,
) -> Option<DecodedField> {
    let slot = |offset| format!("f{}", field_index + offset);

    Some(match &schema.types[inner_type_id] {
        AstType::Primitive(ast) if matches!(ast.name, "Atom" | "Wtf8Atom") => DecodedField {
            width: 2,
            expr: format!("stringAt({}, {})", slot(0), slot(1)),
        },
        AstType::Primitive(ast) if ast.name == "Span" => DecodedField {
            width: 2,
            expr: format!(
                "{} === NONE ? null : {{ start: {}, end: {} }}",
                slot(0),
                slot(0),
                slot(1)
            ),
        },
        AstType::Struct(_) | AstType::Enum(_) | AstType::Box(_) => DecodedField {
            width: 1,
            expr: format!("maybeNode({})", slot(0)),
        },
        AstType::Vec(ast) => DecodedField {
            width: 2,
            expr: if is_option_type(ast.inner_type_id, schema) {
                format!(
                    "{} === NONE ? null : optionalNodeArray({}, {})",
                    slot(0),
                    slot(0),
                    slot(1)
                )
            } else {
                format!(
                    "{} === NONE ? null : nodeArray({}, {})",
                    slot(0),
                    slot(0),
                    slot(1)
                )
            },
        },
        _ => return None,
    })
}

fn decode_primitive_field(name: &str, field_index: usize) -> Option<DecodedField> {
    let slot = |offset| format!("f{}", field_index + offset);

    Some(match name {
        name if matches!(name, "Atom" | "Wtf8Atom") => DecodedField {
            width: 2,
            expr: format!("stringAt({}, {})", slot(0), slot(1)),
        },
        "f64" => DecodedField {
            width: 2,
            expr: format!(
                "(() => {{ const b = new ArrayBuffer(8); const d = new DataView(b); d.setUint32(0, {}, true); d.setUint32(4, {}, true); return d.getFloat64(0, true); }})()",
                slot(0),
                slot(1)
            ),
        },
        _ => return None,
    })
}

fn flag_decode_expr(
    field: &AstStructField,
    offset: usize,
    schema: &Schema,
) -> Option<(String, usize)> {
    let AstType::Primitive(ast) = &schema.types[field.type_id] else {
        return None;
    };

    if ast.name == "bool" {
        return Some((format!("!!(flags & (1 << {offset}))"), 1));
    }

    let (array, width) = simple_enum_flag_array(ast.name)?;
    let mask = (1u32 << width) - 1;
    Some((format!("{array}[(flags >> {offset}) & {mask}]"), width))
}

fn simple_enum_flag_array(name: &str) -> Option<(&'static str, usize)> {
    Some(match name {
        "ImportPhase" => ("IMPORT_PHASE", 2),
        "VarDeclKind" => ("VAR_DECL_KIND", 2),
        "UnaryOp" => ("UNARY_OP", 3),
        "UpdateOp" => ("UPDATE_OP", 1),
        "AssignOp" => ("ASSIGN_OP", 5),
        "BinaryOp" => ("BINARY_OP", 5),
        "MetaPropKind" => ("META_PROP_KIND", 1),
        "MethodKind" => ("METHOD_KIND", 2),
        _ => return None,
    })
}

fn is_option_type(type_id: TypeId, schema: &Schema) -> bool {
    matches!(&schema.types[type_id], AstType::Option(_))
}

fn is_span_type(type_id: TypeId, schema: &Schema) -> bool {
    matches!(&schema.types[type_id], AstType::Primitive(ast) if ast.name == "Span")
}

fn read_node_kinds() -> Vec<String> {
    let source = fs::read_to_string("crates/swc_ecma_ast/src/codec/mod.rs")
        .expect("failed to read codec/mod.rs");
    let mut in_enum = false;
    let mut names = Vec::new();

    for line in source.lines() {
        let line = line.trim();
        if line.starts_with("enum NodeKind") {
            in_enum = true;
            continue;
        }
        if !in_enum || line.starts_with("#[") || line.is_empty() {
            continue;
        }
        if line.starts_with('}') {
            break;
        }
        if let Some(name) = line.trim_end_matches(',').split('=').next() {
            let name = name.trim();
            if !name.is_empty() {
                names.push(name.to_string());
            }
        }
    }

    names
}
