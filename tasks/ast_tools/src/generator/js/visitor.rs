use crate::{
    generator::js::js_field_name,
    output::RawOutput,
    schema::{AstType, Schema, TypeId},
    util::should_skip_field,
};

pub fn js_ast_visitor(schema: &Schema) -> RawOutput {
    let mut methods = Vec::new();

    for ty in schema.types.iter() {
        match ty {
            AstType::Struct(ast) => {
                let method_name = visit_method_name(&ast.name);
                let mut lines = vec![format!("  {method_name}(n: ast.{}): void {{", ast.name)];

                for field in ast.fields.iter() {
                    if should_skip_field(field, schema) || !should_visit_type(field.type_id, schema)
                    {
                        continue;
                    }

                    let visit_method = visit_function_name(field.type_id, schema);
                    lines.push(format!(
                        "    this.{visit_method}(n.{});",
                        js_field_name(&field.name)
                    ));
                }

                lines.push("  }".to_string());
                methods.push(lines.join("\n"));
            }
            AstType::Enum(ast) => {
                let method_name = visit_method_name(&ast.name);
                let mut lines = vec![
                    format!("  {method_name}(n: ast.{}): void {{", ast.name),
                    "    switch (n.type) {".to_string(),
                ];

                for variant in ast.variants.iter() {
                    if let Some(type_id) = variant.type_id {
                        let variant_method = visit_function_name(type_id, schema);
                        for type_name in discriminant_names(type_id, schema) {
                            lines.push(format!(
                                "      case \"{type_name}\": return this.{variant_method}(n);"
                            ));
                        }
                    } else {
                        lines.push(format!("      case \"{}\": return;", variant.name));
                    }
                }

                lines.push("    }".to_string());
                lines.push("  }".to_string());
                methods.push(lines.join("\n"));
            }
            AstType::Vec(ast) => {
                if !should_visit_type(ast.inner_type_id, schema) {
                    continue;
                }

                let method_name = vec_visit_function_name(ast.inner_type_id, schema);
                let ty_ref = type_ref(ast.type_id, schema);
                let item_visit_method = visit_function_name(ast.inner_type_id, schema);
                methods.push(format!(
                    "  {method_name}(n: {ty_ref}): void {{\n    for (const item of n) {{\n      this.{item_visit_method}(item);\n    }}\n  }}"
                ));
            }
            AstType::Option(ast) => {
                if !should_visit_type(ast.inner_type_id, schema) {
                    continue;
                }

                let method_name = option_visit_function_name(ast.inner_type_id, schema);
                let ty_ref = type_ref(ast.type_id, schema);
                let inner_visit_method = visit_function_name(ast.inner_type_id, schema);
                methods.push(format!(
                    "  {method_name}(n: {ty_ref}): void {{\n    if (n !== null) {{\n      this.{inner_visit_method}(n);\n    }}\n  }}"
                ));
            }
            _ => {}
        }
    }

    let content = format!(
        "// generated by tasks/ast_tools/src/generator/js/visitor.rs, do not edit\nimport * as ast from \"./node\";\n\nexport class Visitor {{\n{}\n}}\n",
        methods.join("\n\n")
    );

    RawOutput {
        path: "napi/parser/src-js/visit.ts".to_string(),
        content: content.into_bytes(),
    }
}

fn visit_function_name(type_id: TypeId, schema: &Schema) -> String {
    match &schema.types[type_id] {
        AstType::Struct(ast) => visit_method_name(&ast.name),
        AstType::Enum(ast) => visit_method_name(&ast.name),
        AstType::Box(ast) => visit_function_name(ast.inner_type_id, schema),
        AstType::Vec(ast) => vec_visit_function_name(ast.inner_type_id, schema),
        AstType::Option(ast) => option_visit_function_name(ast.inner_type_id, schema),
        AstType::Primitive(_) => unreachable!(),
    }
}

fn visit_method_name(name: &str) -> String {
    format!("visit{name}")
}

fn discriminant_names(type_id: TypeId, schema: &Schema) -> Vec<String> {
    match &schema.types[type_id] {
        AstType::Struct(ast) => vec![ast.name.clone()],
        AstType::Enum(ast) => ast
            .variants
            .iter()
            .flat_map(|variant| {
                variant
                    .type_id
                    .map(|type_id| discriminant_names(type_id, schema))
                    .unwrap_or_else(|| vec![variant.name.clone()])
            })
            .collect(),
        AstType::Box(ast) => discriminant_names(ast.inner_type_id, schema),
        _ => unreachable!(),
    }
}

fn vec_visit_function_name(inner_type_id: TypeId, schema: &Schema) -> String {
    let inner_type = &schema.types[inner_type_id];
    let name = match inner_type {
        AstType::Option(opt) => {
            let inner_name = option_inner_visit_name(opt.inner_type_id, schema);
            format!("OptVec{inner_name}s")
        }
        _ => format!("{}s", inner_type.name()),
    };

    visit_method_name(&name)
}

fn option_visit_function_name(inner_type_id: TypeId, schema: &Schema) -> String {
    let name = option_inner_visit_name(inner_type_id, schema);

    visit_method_name(&format!("Opt{name}"))
}

fn option_inner_visit_name(type_id: TypeId, schema: &Schema) -> String {
    match &schema.types[type_id] {
        AstType::Box(ast) => option_inner_visit_name(ast.inner_type_id, schema),
        AstType::Vec(ast) => {
            let inner_name = option_inner_visit_name(ast.inner_type_id, schema);
            format!("{inner_name}s")
        }
        ty => ty.name().to_string(),
    }
}

fn type_ref(type_id: TypeId, schema: &Schema) -> String {
    match &schema.types[type_id] {
        AstType::Struct(ast) => format!("ast.{}", ast.name),
        AstType::Enum(ast) => format!("ast.{}", ast.name),
        AstType::Box(ast) => type_ref(ast.inner_type_id, schema),
        AstType::Vec(ast) => {
            let inner = type_ref(ast.inner_type_id, schema);
            if inner.contains(" | ") {
                format!("({inner})[]")
            } else {
                format!("{inner}[]")
            }
        }
        AstType::Option(ast) => format!("{} | null", type_ref(ast.inner_type_id, schema)),
        AstType::Primitive(ast) => match ast.name {
            "Atom" | "Wtf8Atom" => "string".to_string(),
            "Span" => "ast.Span".to_string(),
            "bool" => "boolean".to_string(),
            "f64" => "number".to_string(),
            name => format!("ast.{name}"),
        },
    }
}

fn should_visit_type(type_id: TypeId, schema: &Schema) -> bool {
    match &schema.types[type_id] {
        AstType::Struct(_) | AstType::Enum(_) => true,
        AstType::Box(ast) => should_visit_type(ast.inner_type_id, schema),
        AstType::Vec(ast) => should_visit_type(ast.inner_type_id, schema),
        AstType::Option(ast) => should_visit_type(ast.inner_type_id, schema),
        AstType::Primitive(_) => false,
    }
}
