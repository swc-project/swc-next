use crate::{
    generator::js::js_field_name,
    output::RawOutput,
    schema::{AstStruct, AstStructField, AstType, Schema, TypeId},
    util::{is_span_field, should_skip_field, simple_enum_flag_width},
};

pub fn ast_measure(schema: &Schema) -> RawOutput {
    let mut cases = String::new();
    for ty in schema.types.iter() {
        if let AstType::Struct(ast) = ty {
            cases.push_str(&generate_measure_for_struct(ast, schema));
        }
    }

    let content = format!(
        r#"// generated by tasks/ast_tools/src/generator/js/measure.rs, do not edit
export function measure(measurement, node) {{
  if (node == null) return;

  switch (node.type) {{
{cases}
    default:
      throw new Error(`Unknown node type ${{node.type}}`);
  }}
}}

export default measure;
"#
    );

    RawOutput {
        path: "napi/parser/src-js/generated/measure.js".to_string(),
        content: content.into_bytes(),
    }
}

fn generate_measure_for_struct(ast: &AstStruct, schema: &Schema) -> String {
    let mut lines = vec![
        format!("    case \"{}\": {{", ast.name),
        "      measurement.node();".to_string(),
    ];

    for field in ast.fields.iter() {
        if is_span_field(field, schema) || should_skip_field(field, schema) {
            continue;
        }

        if is_flag_field(field, schema) {
            continue;
        }

        if let Some(stmt) = measure_field_stmt(field, schema) {
            lines.push(format!("      {stmt}"));
        }
    }

    lines.push("      return;".to_string());
    lines.push("    }".to_string());
    lines.join("\n") + "\n"
}

fn measure_field_stmt(field: &AstStructField, schema: &Schema) -> Option<String> {
    let field_name = js_field_name(&field.name);

    Some(match &schema.types[field.type_id] {
        AstType::Struct(_) | AstType::Enum(_) | AstType::Box(_) => {
            format!("measure(measurement, node.{field_name});")
        }
        AstType::Vec(_) => format!("measurement.nodes(node.{field_name});"),
        AstType::Option(ast) => measure_option_field_stmt(&field_name, ast.inner_type_id, schema)?,
        AstType::Primitive(ast) => measure_primitive_field_stmt(&field_name, ast.name)?,
    })
}

fn measure_option_field_stmt(
    field_name: &str,
    inner_type_id: TypeId,
    schema: &Schema,
) -> Option<String> {
    Some(match &schema.types[inner_type_id] {
        AstType::Primitive(ast) if matches!(ast.name, "Atom" | "Wtf8Atom") => {
            format!("measurement.optString(node.{field_name});")
        }
        AstType::Struct(_) | AstType::Enum(_) | AstType::Box(_) => {
            format!("measure(measurement, node.{field_name});")
        }
        AstType::Vec(_) => {
            format!("if (node.{field_name} != null) measurement.nodes(node.{field_name});")
        }
        _ => return None,
    })
}

fn measure_primitive_field_stmt(field_name: &str, name: &str) -> Option<String> {
    Some(match name {
        "Atom" | "Wtf8Atom" => format!("measurement.string(node.{field_name});"),
        _ => return None,
    })
}

fn is_flag_field(field: &AstStructField, schema: &Schema) -> bool {
    let AstType::Primitive(ast) = &schema.types[field.type_id] else {
        return false;
    };

    ast.name == "bool" || simple_enum_flag_width(ast.name).is_some()
}
