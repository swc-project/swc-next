use std::fs;

use crate::{
    generator::js::js_field_name,
    output::RawOutput,
    schema::{AstStruct, AstStructField, AstType, Schema, SpanKind, TypeId},
    util::{is_span_field, should_skip_field, simple_enum_flag_width},
};

pub fn ast_encode(schema: &Schema) -> RawOutput {
    let node_kinds = read_node_kinds();
    let node_kind_entries = node_kinds
        .iter()
        .enumerate()
        .map(|(index, name)| format!("  {name}: {index},"))
        .collect::<Vec<_>>()
        .join("\n");

    let enum_maps = generate_simple_enum_maps(schema);

    let mut cases = String::new();
    for ty in schema.types.iter() {
        if let AstType::Struct(ast) = ty {
            cases.push_str(&generate_encode_for_struct(ast, schema));
        }
    }

    let content = format!(
        r#"// generated by tasks/ast_tools/src/generator/js/encode.rs, do not edit
const NONE = 0xffffffff;
const NK = {{
{node_kind_entries}
}};
{enum_maps}

function f64Parts(value) {{
  const buffer = new ArrayBuffer(8);
  const view = new DataView(buffer);
  view.setFloat64(0, value, true);
  return [view.getUint32(0, true), view.getUint32(4, true)];
}}

export function encode(encoder, node) {{
  if (node == null) return NONE;

  switch (node.type) {{
{cases}
    default:
      throw new Error(`Unknown node type ${{node.type}}`);
  }}
}}

export default encode;
"#
    );

    RawOutput {
        path: "napi/parser/src-js/generated/encode.js".to_string(),
        content: content.into_bytes(),
    }
}

fn generate_encode_for_struct(ast: &AstStruct, schema: &Schema) -> String {
    let mut flag_offset = 0usize;
    let mut flags = Vec::new();
    let mut pre_stmts = Vec::new();
    let mut fields = Vec::new();

    for field in ast.fields.iter() {
        if is_span_field(field, schema) || should_skip_field(field, schema) {
            continue;
        }

        if let Some((expr, width)) = flag_expr(field, flag_offset, schema) {
            flags.push(expr);
            flag_offset += width;
            continue;
        }

        let Some(encoded) = field_exprs(field, schema) else {
            unreachable!("{} has unsupported field {}", ast.name, field.name);
        };
        if !encoded.stmts.is_empty() {
            pre_stmts.push(encoded.stmts);
        }
        fields.extend(encoded.exprs);
    }

    if fields.len() > 5 || flag_offset > u16::BITS as usize {
        unreachable!("{} cannot fit in PackedNode", ast.name);
    }

    let mut lines = vec![format!("    case \"{}\": {{", ast.name)];
    lines.extend(pre_stmts.into_iter().map(|stmt| indent(&stmt, 6)));

    for (index, expr) in fields.iter().enumerate() {
        lines.push(format!("      const field{index} = {expr};"));
    }

    let flags_expr = if flags.is_empty() {
        "0".to_string()
    } else {
        flags.join(" | ")
    };
    lines.push(format!("      const flags = {flags_expr};"));
    lines.extend(
        span_stmt(ast, schema)
            .into_iter()
            .map(|stmt| indent(&stmt, 6)),
    );

    lines.push("      return encoder.packedNode({".to_string());
    lines.push(format!("        kind: NK.{},", ast.name));
    lines.push("        flags,".to_string());
    lines.push("        span_lo,".to_string());
    lines.push("        span_hi,".to_string());
    for index in 0..fields.len() {
        lines.push(format!("        field{index},"));
    }
    lines.push("      });".to_string());
    lines.push("    }".to_string());
    lines.join("\n") + "\n"
}

struct EncodedField {
    stmts: String,
    exprs: Vec<String>,
}

fn encoded_expr(expr: String) -> EncodedField {
    EncodedField {
        stmts: String::new(),
        exprs: vec![expr],
    }
}

fn field_exprs(field: &AstStructField, schema: &Schema) -> Option<EncodedField> {
    let field_name = js_field_name(&field.name);

    Some(match &schema.types[field.type_id] {
        AstType::Struct(_) | AstType::Enum(_) | AstType::Box(_) => {
            encoded_expr(format!("encode(encoder, node.{field_name})"))
        }
        AstType::Vec(_) => list_field_exprs(&field.name, format!("node.{field_name}")),
        AstType::Option(ast) => {
            option_field_exprs(&field.name, &field_name, ast.inner_type_id, schema)?
        }
        AstType::Primitive(ast) => primitive_field_exprs(&field.name, &field_name, ast.name)?,
    })
}

fn list_field_exprs(name: &str, value: String) -> EncodedField {
    let start = format!("__{}_start", name);
    let len = format!("__{}_len", name);
    EncodedField {
        stmts: format!("const [{start}, {len}] = encoder.nodes({value});"),
        exprs: vec![start, len],
    }
}

fn string_field_exprs(name: &str, callee: String) -> EncodedField {
    let start = format!("__{}_start", name);
    let len = format!("__{}_len", name);
    EncodedField {
        stmts: format!("const [{start}, {len}] = {callee};"),
        exprs: vec![start, len],
    }
}

fn option_field_exprs(
    raw_field_name: &str,
    field_name: &str,
    inner_type_id: TypeId,
    schema: &Schema,
) -> Option<EncodedField> {
    Some(match &schema.types[inner_type_id] {
        AstType::Primitive(ast) if ast.name == "Atom" => string_field_exprs(
            raw_field_name,
            format!("encoder.optUtf8(node.{field_name})"),
        ),
        AstType::Primitive(ast) if ast.name == "Wtf8Atom" => string_field_exprs(
            raw_field_name,
            format!("encoder.optWtf8(node.{field_name})"),
        ),
        AstType::Primitive(ast) if ast.name == "Span" => string_field_exprs(
            raw_field_name,
            format!("encoder.optSpan(node.{field_name})"),
        ),
        AstType::Struct(_) | AstType::Enum(_) | AstType::Box(_) => encoded_expr(format!(
            "node.{field_name} == null ? NONE : encode(encoder, node.{field_name})"
        )),
        AstType::Vec(_) => {
            let start = format!("__{}_start", raw_field_name);
            let len = format!("__{}_len", raw_field_name);
            EncodedField {
                stmts: format!(
                    "const [{start}, {len}] = node.{field_name} == null ? [NONE, 0] : encoder.nodes(node.{field_name});"
                ),
                exprs: vec![start, len],
            }
        }
        _ => return None,
    })
}

fn primitive_field_exprs(
    raw_field_name: &str,
    field_name: &str,
    name: &str,
) -> Option<EncodedField> {
    Some(match name {
        "Atom" => string_field_exprs(raw_field_name, format!("encoder.utf8(node.{field_name})")),
        "Wtf8Atom" => {
            string_field_exprs(raw_field_name, format!("encoder.wtf8(node.{field_name})"))
        }
        "f64" => {
            let lo = format!("__{}_lo", raw_field_name);
            let hi = format!("__{}_hi", raw_field_name);
            EncodedField {
                stmts: format!("const [{lo}, {hi}] = f64Parts(node.{field_name});"),
                exprs: vec![lo, hi],
            }
        }
        _ => return None,
    })
}

fn flag_expr(field: &AstStructField, offset: usize, schema: &Schema) -> Option<(String, usize)> {
    let AstType::Primitive(ast) = &schema.types[field.type_id] else {
        return None;
    };

    let field_name = js_field_name(&field.name);
    if ast.name == "bool" {
        return Some((format!("(node.{field_name} ? (1 << {offset}) : 0)"), 1));
    }

    let width = simple_enum_flag_width(ast.name)?;
    let map_name = simple_enum_flag_map_name(ast.name)?;
    Some((
        format!("({map_name}[node.{field_name}] << {offset})"),
        width,
    ))
}

fn span_stmt(ast: &AstStruct, schema: &Schema) -> Vec<String> {
    match span_expr(ast, schema) {
        Some(expr) => vec![format!("const [span_lo, span_hi] = encoder.span({expr});")],
        None => vec![
            "const span_lo = 0;".to_string(),
            "const span_hi = 0;".to_string(),
        ],
    }
}

fn span_expr(ast: &AstStruct, schema: &Schema) -> Option<String> {
    let full_fields = ast
        .fields
        .iter()
        .filter(|field| field.span_kind == Some(SpanKind::Full))
        .collect::<Vec<_>>();
    let lo_fields = ast
        .fields
        .iter()
        .filter(|field| field.span_kind == Some(SpanKind::Lo))
        .collect::<Vec<_>>();
    let hi_fields = ast
        .fields
        .iter()
        .filter(|field| field.span_kind == Some(SpanKind::Hi))
        .collect::<Vec<_>>();

    assert!(
        full_fields.len() <= 1,
        "{} has multiple #[span] fields",
        ast.name
    );
    assert!(
        lo_fields.len() <= 1,
        "{} has multiple #[span(lo)] fields",
        ast.name
    );
    assert!(
        hi_fields.len() <= 1,
        "{} has multiple #[span(hi)] fields",
        ast.name
    );
    assert!(
        full_fields.is_empty() || (lo_fields.is_empty() && hi_fields.is_empty()),
        "{} mixes #[span] with #[span(lo)] / #[span(hi)]",
        ast.name
    );

    if let Some(field) = full_fields.first() {
        return Some(field_span_expr(field, schema));
    }

    if !lo_fields.is_empty() || !hi_fields.is_empty() {
        assert!(
            !lo_fields.is_empty() && !hi_fields.is_empty(),
            "{} must have both #[span(lo)] and #[span(hi)]",
            ast.name
        );
        return Some(format!(
            "{{ start: {}, end: {} }}",
            field_span_endpoint_expr(lo_fields[0], SpanKind::Lo, schema),
            field_span_endpoint_expr(hi_fields[0], SpanKind::Hi, schema)
        ));
    }

    ast.fields
        .iter()
        .find(|field| field.name == "span" && is_span_field(field, schema))
        .map(|field| field_span_expr(field, schema))
}

fn field_span_expr(field: &AstStructField, schema: &Schema) -> String {
    let field_name = js_field_name(&field.name);
    if is_span_field(field, schema) {
        format!("node.{field_name}")
    } else {
        format!("node.{field_name}.span")
    }
}

fn field_span_endpoint_expr(
    field: &AstStructField,
    span_kind: SpanKind,
    schema: &Schema,
) -> String {
    let field_name = js_field_name(&field.name);
    match span_kind {
        SpanKind::Lo => {
            if is_span_field(field, schema) {
                format!("node.{field_name}.start")
            } else {
                format!("node.{field_name}.span.start")
            }
        }
        SpanKind::Hi => {
            if is_span_field(field, schema) {
                format!("node.{field_name}.end")
            } else {
                format!("node.{field_name}.span.end")
            }
        }
        SpanKind::Full => unreachable!("full span is not an endpoint"),
    }
}

fn generate_simple_enum_maps(schema: &Schema) -> String {
    schema
        .types
        .iter()
        .filter_map(|ty| {
            let AstType::Primitive(ast) = ty else {
                return None;
            };
            let map_name = simple_enum_flag_map_name(ast.name)?;
            let variants = ast.variants.as_ref()?;
            let entries = variants
                .iter()
                .enumerate()
                .map(|(index, variant)| format!("  {variant}: {index},"))
                .collect::<Vec<_>>()
                .join("\n");
            Some(format!("const {map_name} = {{\n{entries}\n}};"))
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn simple_enum_flag_map_name(name: &str) -> Option<&'static str> {
    Some(match name {
        "ImportPhase" => "IMPORT_PHASE",
        "VarDeclKind" => "VAR_DECL_KIND",
        "UnaryOp" => "UNARY_OP",
        "UpdateOp" => "UPDATE_OP",
        "AssignOp" => "ASSIGN_OP",
        "BinaryOp" => "BINARY_OP",
        "MetaPropKind" => "META_PROP_KIND",
        "MethodKind" => "METHOD_KIND",
        _ => return None,
    })
}

fn read_node_kinds() -> Vec<String> {
    let source = fs::read_to_string("crates/swc_ecma_ast/src/codec/mod.rs")
        .expect("failed to read codec/mod.rs");
    let mut in_enum = false;
    let mut names = Vec::new();

    for line in source.lines() {
        let line = line.trim();
        if line.starts_with("enum NodeKind") {
            in_enum = true;
            continue;
        }
        if !in_enum || line.starts_with("#[") || line.is_empty() {
            continue;
        }
        if line.starts_with('}') {
            break;
        }
        if let Some(name) = line.trim_end_matches(',').split('=').next() {
            let name = name.trim();
            if !name.is_empty() {
                names.push(name.to_string());
            }
        }
    }

    names
}

fn indent(text: &str, spaces: usize) -> String {
    let prefix = " ".repeat(spaces);
    text.lines()
        .map(|line| format!("{prefix}{line}"))
        .collect::<Vec<_>>()
        .join("\n")
}
