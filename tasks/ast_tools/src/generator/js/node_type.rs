use crate::{
    generator::js::js_field_name,
    output::RawOutput,
    schema::{AstEnum, AstStruct, AstType, Schema, TypeId},
    util::should_skip_field,
};

pub fn ast_node_type(schema: &Schema) -> RawOutput {
    let mut definitions =
        vec!["export interface Span {\n  start: number;\n  end: number;\n}".to_string()];

    for ty in schema.types.iter() {
        match ty {
            AstType::Struct(ast) => definitions.push(generate_node_interface(ast, schema)),
            AstType::Enum(ast) => definitions.push(generate_node_type_alias(ast, schema)),
            AstType::Primitive(ast) if let Some(variants) = &ast.variants => {
                let variants = variants
                    .iter()
                    .map(|variant| format!("\"{variant}\""))
                    .collect::<Vec<_>>()
                    .join(" | ");
                definitions.push(format!("export type {} = {variants};", ast.name));
            }
            _ => {}
        }
    }

    let content = format!(
        "// generated by tasks/ast_tools/src/generator/js/node_type.rs, do not edit\n{}\n",
        definitions.join("\n\n")
    );

    RawOutput {
        path: "napi/parser/src-js/node.ts".to_string(),
        content: content.into_bytes(),
    }
}

fn generate_node_interface(ast: &AstStruct, schema: &Schema) -> String {
    let mut fields = Vec::new();

    for field in ast.fields.iter() {
        if should_skip_field(field, schema) {
            continue;
        }

        let ty = node_field_type(field.type_id, schema)
            .unwrap_or_else(|| unreachable!("{} has unsupported field {}", ast.name, field.name));
        fields.push(format!("  {}: {ty};", js_field_name(&field.name)));
    }

    let mut lines = vec![
        format!("export interface {} {{", ast.name),
        format!("  type: \"{}\";", ast.name),
    ];
    lines.extend(fields);
    lines.push("}".to_string());
    lines.join("\n")
}

fn generate_node_type_alias(ast: &AstEnum, schema: &Schema) -> String {
    let variants = ast
        .variants
        .iter()
        .map(|variant| match variant.type_id {
            Some(type_id) => node_type_ref(type_id, schema).unwrap_or_else(|| {
                unreachable!("{} has unsupported variant {}", ast.name, variant.name)
            }),
            None => unreachable!("{} cannot contain unit variant {}", ast.name, variant.name),
        })
        .collect::<Vec<_>>();

    format!("export type {} = {};", ast.name, variants.join(" | "))
}

fn node_field_type(type_id: TypeId, schema: &Schema) -> Option<String> {
    match &schema.types[type_id] {
        AstType::Option(ast) => Some(format!(
            "{} | null",
            node_type_ref(ast.inner_type_id, schema)?
        )),
        _ => node_type_ref(type_id, schema),
    }
}

fn node_type_ref(type_id: TypeId, schema: &Schema) -> Option<String> {
    Some(match &schema.types[type_id] {
        AstType::Struct(ast) => ast.name.clone(),
        AstType::Enum(ast) => ast.name.clone(),
        AstType::Box(ast) => node_type_ref(ast.inner_type_id, schema)?,
        AstType::Vec(ast) => {
            let inner = node_field_type(ast.inner_type_id, schema)?;
            if inner.contains(" | ") {
                format!("({inner})[]")
            } else {
                format!("{inner}[]")
            }
        }
        AstType::Option(ast) => format!("{} | null", node_type_ref(ast.inner_type_id, schema)?),
        AstType::Primitive(ast) => match ast.name {
            "Atom" | "Wtf8Atom" => "string".to_string(),
            "Span" => "Span".to_string(),
            "bool" => "boolean".to_string(),
            "f64" => "number".to_string(),
            name => name.to_string(),
        },
    })
}
