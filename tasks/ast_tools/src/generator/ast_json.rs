use convert_case::{Case, Casing};
use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use crate::{
    AST_CRATE_PATH,
    output::{RawOutput, RustOutput, output_path},
    schema::{AstType, Schema},
    util::safe_ident,
};

/// Print the Rust AST schema without applying ESTree projections or skips.
pub fn ast_json(schema: &Schema) -> RawOutput {
    let mut impls = TokenStream::new();
    let mut node_arms = TokenStream::new();
    let mut kind_arms = TokenStream::new();
    for ty in &schema.types {
        let name = ty.repr_ident(schema);
        match ty {
            AstType::Struct(node) => {
                let prefix = format!("{{\"type\":\"{}\",\"span\":", node.name);
                let fields = node.fields.iter().map(|field| {
                    let getter = safe_ident(&field.name.to_case(Case::Snake));
                    let field_name = field.name.strip_prefix("r#").unwrap_or(&field.name);
                    let key = format!(",\"{field_name}\":");
                    quote! {
                        output.push_str(#key);
                        self.#getter(ast).print_json(ast, output);
                    }
                });
                impls.extend(quote! {
                    impl JsonPrint for #name {
                        fn print_json(self, ast: &Ast<'_>, output: &mut String) {
                            output.push_str(#prefix);
                            self.span(ast).print_json(ast, output);
                            #(#fields)*
                            output.push('}');
                        }
                    }
                });
                node_arms.extend(quote!(Self::#name(node) => node.print_json(ast, output),));
                let kind = format!("\"{}\"", node.name);
                kind_arms.extend(quote!(Self::#name => #kind,));
            }
            AstType::Enum(node) => {
                let data = format_ident!("{}Data", node.name);
                let accessor = format_ident!("{}_data", node.name.to_case(Case::Snake));
                let arms = node.variants.iter().map(|variant| {
                    let variant = format_ident!("{}", variant.name);
                    quote!(Self::#variant(node) => node.print_json(ast, output),)
                });
                impls.extend(quote! {
                    impl JsonPrint for #name {
                        fn print_json(self, ast: &Ast<'_>, output: &mut String) {
                            ast.#accessor(self).print_json(ast, output);
                        }
                    }

                    impl JsonPrint for #data {
                        fn print_json(self, ast: &Ast<'_>, output: &mut String) {
                            match self { #(#arms)* }
                        }
                    }
                });
            }
            // Generic containers and primitives are implemented in json.rs.
            _ => {}
        }
    }

    for enumeration in &schema.scalar_enums {
        let name = format_ident!("{}", enumeration.name);
        let arms = enumeration.variants.iter().map(|variant| {
            let name = format_ident!("{}", variant.name);
            let value = format!("\"{}\"", variant.name);
            quote!(Self::#name => #value,)
        });
        impls.extend(quote! {
            impl JsonPrint for #name {
                fn print_json(self, _ast: &Ast<'_>, output: &mut String) {
                    output.push_str(match self { #(#arms)* });
                }
            }
        });
    }

    RustOutput {
        path: output_path(AST_CRATE_PATH, "ast_json"),
        tokens: quote! {
            //! Generated by ast_tools. Do not edit by hand.
            use crate::*;
            use crate::json::JsonPrint;

            #impls

            impl JsonPrint for NodeKindData {
                fn print_json(self, ast: &Ast<'_>, output: &mut String) {
                    match self { #node_arms }
                }
            }

            impl JsonPrint for NodeKind {
                fn print_json(self, _ast: &Ast<'_>, output: &mut String) {
                    output.push_str(match self { #kind_arms });
                }
            }
        },
    }
    .into()
}
