use std::{
    collections::{BTreeMap, BTreeSet, HashMap, HashSet},
    fmt::Write,
};

use anyhow::{Context, Result, bail};

use super::descriptor::{BridgeDescriptor, BridgeFunction, StringEnum, WireDirection};

const GENERATED_HEADER: &str = "// Generated by bridge_cli. Do not edit.\n";

pub(super) fn render_binding(descriptors: Vec<BridgeDescriptor>, runtime: &str) -> Result<String> {
    let mut functions = Vec::new();
    let mut enums = BTreeMap::new();
    let mut decode_wires = HashMap::new();
    let mut encode_wires = HashMap::new();

    for descriptor in descriptors {
        match descriptor {
            BridgeDescriptor::Function(function) => functions.push(function),
            BridgeDescriptor::StringEnum(enumeration) => {
                if enums
                    .insert(enumeration.rust_name.clone(), enumeration)
                    .is_some()
                {
                    bail!("duplicate bridge string enum metadata");
                }
            }
            BridgeDescriptor::WireMapping(mapping) => {
                let mappings = match mapping.direction {
                    WireDirection::Decode => &mut decode_wires,
                    WireDirection::Encode => &mut encode_wires,
                };
                if mappings
                    .insert(mapping.semantic_type.clone(), mapping.wire_type)
                    .is_some()
                {
                    bail!(
                        "duplicate bridge wire mapping for {}",
                        mapping.semantic_type
                    );
                }
            }
        }
    }

    if functions.is_empty() {
        bail!("bridge metadata contains no functions");
    }
    functions.sort_by(|left, right| left.js_name.cmp(&right.js_name));

    let context = RenderContext {
        enums: &enums,
        decode_wires: &decode_wires,
        encode_wires: &encode_wires,
    };
    let usage = Usage::collect(&functions, &context)?;
    let mut source = String::from(GENERATED_HEADER);
    writeln!(
        source,
        "import {{ {} }} from {};\n",
        usage
            .runtime_imports
            .iter()
            .cloned()
            .collect::<Vec<_>>()
            .join(", "),
        js_string(&format!("./{runtime}"))
    )
    .unwrap();

    for enumeration in enums.values() {
        render_enum(
            &mut source,
            enumeration,
            usage.used_enums.contains(&enumeration.rust_name),
        );
        source.push('\n');
    }

    for (index, function) in functions.iter().enumerate() {
        render_function(&mut source, function, &context)?;
        if index + 1 != functions.len() {
            source.push('\n');
        }
    }
    render_helpers(&mut source, &usage);
    Ok(source)
}

struct RenderContext<'a> {
    enums: &'a BTreeMap<String, StringEnum>,
    decode_wires: &'a HashMap<String, String>,
    encode_wires: &'a HashMap<String, String>,
}

#[derive(Clone, Copy)]
enum WireKind<'a> {
    Unit,
    U32,
    I32,
    F64,
    Bool,
    String,
    Bytes,
    StringEnum(&'a StringEnum),
}

struct Usage {
    runtime_imports: BTreeSet<&'static str>,
    used_enums: HashSet<String>,
    encode_u32: bool,
    encode_i32: bool,
    encode_f64: bool,
    encode_boolean: bool,
    encode_enum: bool,
    decode_enum: bool,
}

impl Usage {
    fn collect(functions: &[BridgeFunction], context: &RenderContext<'_>) -> Result<Self> {
        let mut usage = Self {
            runtime_imports: BTreeSet::from(["getFunction"]),
            used_enums: HashSet::new(),
            encode_u32: false,
            encode_i32: false,
            encode_f64: false,
            encode_boolean: false,
            encode_enum: false,
            decode_enum: false,
        };

        for function in functions {
            for parameter in &function.parameters {
                match context.decode_kind(&parameter.semantic_type)? {
                    WireKind::String => {
                        usage.runtime_imports.insert("withEncodedString");
                    }
                    WireKind::Bytes => {
                        usage.runtime_imports.insert("withEncodedBytes");
                    }
                    WireKind::StringEnum(enumeration) => {
                        usage.encode_enum = true;
                        usage.used_enums.insert(enumeration.rust_name.clone());
                    }
                    WireKind::U32 => usage.encode_u32 = true,
                    WireKind::I32 => usage.encode_i32 = true,
                    WireKind::F64 => usage.encode_f64 = true,
                    WireKind::Bool => usage.encode_boolean = true,
                    WireKind::Unit => {}
                }
            }

            let result_kind = context.encode_kind(&function.result)?;
            if function.fallible {
                usage.runtime_imports.insert("takeFallibleResult");
                match result_kind {
                    WireKind::String => {
                        usage.runtime_imports.insert("decodeString");
                    }
                    WireKind::U32 | WireKind::StringEnum(_) | WireKind::Bool => {
                        usage.runtime_imports.insert("decodeU32");
                    }
                    WireKind::I32 => {
                        usage.runtime_imports.insert("decodeI32");
                    }
                    WireKind::F64 => {
                        usage.runtime_imports.insert("decodeF64");
                    }
                    WireKind::Unit | WireKind::Bytes => {}
                }
            } else {
                match result_kind {
                    WireKind::Bytes => {
                        usage.runtime_imports.insert("takeBytes");
                    }
                    WireKind::String => {
                        usage.runtime_imports.insert("takeString");
                    }
                    WireKind::Unit
                    | WireKind::U32
                    | WireKind::I32
                    | WireKind::F64
                    | WireKind::Bool
                    | WireKind::StringEnum(_) => {}
                }
            }
            if matches!(result_kind, WireKind::Bool) {
                usage.runtime_imports.insert("decodeBoolean");
            }
            if let WireKind::StringEnum(enumeration) = result_kind {
                usage.decode_enum = true;
                usage.used_enums.insert(enumeration.rust_name.clone());
            }
        }
        Ok(usage)
    }
}

impl RenderContext<'_> {
    fn decode_kind(&self, semantic_type: &str) -> Result<WireKind<'_>> {
        self.resolve_kind(semantic_type, self.decode_wires)
    }

    fn encode_kind(&self, semantic_type: &str) -> Result<WireKind<'_>> {
        self.resolve_kind(semantic_type, self.encode_wires)
    }

    fn resolve_kind<'a>(
        &'a self,
        semantic_type: &str,
        mappings: &'a HashMap<String, String>,
    ) -> Result<WireKind<'a>> {
        if let Some(kind) = self.direct_kind(semantic_type) {
            return Ok(kind);
        }
        let wire_type = mappings
            .get(semantic_type)
            .context("missing bridge wire mapping")?;
        self.direct_kind(wire_type)
            .context("unsupported bridge wire type")
    }

    fn direct_kind(&self, ty: &str) -> Option<WireKind<'_>> {
        match ty {
            "()" => Some(WireKind::Unit),
            "u32" => Some(WireKind::U32),
            "i32" => Some(WireKind::I32),
            "f64" => Some(WireKind::F64),
            "bool" => Some(WireKind::Bool),
            "String" => Some(WireKind::String),
            "Vec<u8>" => Some(WireKind::Bytes),
            _ => self.enums.get(ty).map(WireKind::StringEnum),
        }
    }
}

fn render_enum(source: &mut String, enumeration: &StringEnum, render_values: bool) {
    writeln!(
        source,
        "export const {} = Object.defineProperties({{}}, {{",
        enumeration.js_name
    )
    .unwrap();
    for variant in &enumeration.variants {
        writeln!(
            source,
            "  {}: {{ value: {} }},",
            variant.rust_name,
            js_string(&variant.js_value)
        )
        .unwrap();
    }
    source.push_str("});\n");
    if render_values {
        writeln!(
            source,
            "const {}Values = [{}];",
            lower_camel(&enumeration.js_name),
            enumeration
                .variants
                .iter()
                .map(|variant| js_string(&variant.js_value))
                .collect::<Vec<_>>()
                .join(", ")
        )
        .unwrap();
    }
}

fn render_function(
    source: &mut String,
    function: &BridgeFunction,
    context: &RenderContext<'_>,
) -> Result<()> {
    let parameter_names = function
        .parameters
        .iter()
        .map(|parameter| parameter.js_name.as_str())
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(
        source,
        "export function {}({parameter_names}) {{",
        function.js_name
    )
    .unwrap();
    writeln!(
        source,
        "  const call = getFunction({});",
        js_string(&function.wasm_export_name)
    )
    .unwrap();

    let mut call_arguments = Vec::new();
    let mut allocations = Vec::new();
    for parameter in &function.parameters {
        let kind = context.decode_kind(&parameter.semantic_type)?;
        let name = &parameter.js_name;
        match kind {
            WireKind::String => {
                writeln!(
                    source,
                    "  if (typeof {name} !== \"string\") throw new TypeError({});",
                    js_string(&format!("{name} must be a string"))
                )
                .unwrap();
                let pointer = format!("{name}Pointer");
                call_arguments.push(pointer.clone());
                allocations.push(("withEncodedString", name.as_str(), pointer));
            }
            WireKind::Bytes => {
                writeln!(
                    source,
                    "  if (!({name} instanceof Uint8Array)) throw new TypeError({});",
                    js_string(&format!("{name} must be a Uint8Array"))
                )
                .unwrap();
                let pointer = format!("{name}Pointer");
                call_arguments.push(pointer.clone());
                allocations.push(("withEncodedBytes", name.as_str(), pointer));
            }
            WireKind::StringEnum(enumeration) => call_arguments.push(format!(
                "encodeEnum({name}, {}Values, {})",
                lower_camel(&enumeration.js_name),
                js_string(name)
            )),
            WireKind::U32 => {
                call_arguments.push(format!("encodeU32({name}, {})", js_string(name)));
            }
            WireKind::I32 => {
                call_arguments.push(format!("encodeI32({name}, {})", js_string(name)));
            }
            WireKind::F64 => {
                call_arguments.push(format!("encodeF64({name}, {})", js_string(name)));
            }
            WireKind::Bool => {
                call_arguments.push(format!("encodeBoolean({name}, {})", js_string(name)));
            }
            WireKind::Unit => {
                bail!(
                    "unit is not supported as parameter `{}` of `{}`",
                    parameter.rust_name,
                    function.rust_name
                );
            }
        }
    }

    let call = render_call(&call_arguments, &allocations, 2);
    let result_kind = context.encode_kind(&function.result)?;
    if function.fallible {
        writeln!(source, "  const resultPointer = ({call}) >>> 0;").unwrap();
        source.push_str("  const payload = takeFallibleResult(resultPointer);\n");
        render_payload_result(source, result_kind);
    } else {
        render_direct_result(source, result_kind, &call);
    }
    source.push_str("}\n");
    Ok(())
}

fn render_direct_result(source: &mut String, kind: WireKind<'_>, call: &str) {
    match kind {
        WireKind::Unit => writeln!(source, "  {call};").unwrap(),
        WireKind::Bytes => {
            writeln!(source, "  const resultPointer = ({call}) >>> 0;").unwrap();
            source.push_str("  return takeBytes(resultPointer);\n");
        }
        WireKind::String => {
            writeln!(source, "  const resultPointer = ({call}) >>> 0;").unwrap();
            source.push_str("  return takeString(resultPointer);\n");
        }
        WireKind::StringEnum(enumeration) => {
            writeln!(source, "  const result = ({call}) >>> 0;").unwrap();
            writeln!(
                source,
                "  return decodeEnum(result, {}Values, {});",
                lower_camel(&enumeration.js_name),
                js_string(&lower_words(&enumeration.rust_name))
            )
            .unwrap();
        }
        WireKind::U32 => writeln!(source, "  return ({call}) >>> 0;").unwrap(),
        WireKind::I32 => writeln!(source, "  return ({call}) | 0;").unwrap(),
        WireKind::F64 => writeln!(source, "  return {call};").unwrap(),
        WireKind::Bool => writeln!(source, "  return decodeBoolean({call});").unwrap(),
    }
}

fn render_payload_result(source: &mut String, kind: WireKind<'_>) {
    match kind {
        WireKind::Unit => source.push_str("  if (payload.byteLength !== 0) throw new RangeError(\"WebAssembly bridge returned an invalid unit result\");\n  return;\n"),
        WireKind::Bytes => source.push_str("  return payload;\n"),
        WireKind::String => source.push_str("  return decodeString(payload);\n"),
        WireKind::StringEnum(enumeration) => {
            writeln!(
                source,
                "  return decodeEnum(decodeU32(payload), {}Values, {});",
                lower_camel(&enumeration.js_name),
                js_string(&lower_words(&enumeration.rust_name))
            )
            .unwrap();
        }
        WireKind::U32 => source.push_str("  return decodeU32(payload);\n"),
        WireKind::I32 => source.push_str("  return decodeI32(payload);\n"),
        WireKind::F64 => source.push_str("  return decodeF64(payload);\n"),
        WireKind::Bool => source.push_str("  return decodeBoolean(decodeU32(payload));\n"),
    }
}

fn render_call(
    call_arguments: &[String],
    allocations: &[(&str, &str, String)],
    indentation: usize,
) -> String {
    let Some(((helper, value, pointer), remaining)) = allocations.split_first() else {
        return format!("call({})", call_arguments.join(", "));
    };
    let nested = render_call(call_arguments, remaining, indentation + 2);
    format!(
        "{helper}(\n{inner_indent}{value},\n{inner_indent}({pointer}) => {nested},\n{indent})",
        inner_indent = " ".repeat(indentation + 2),
        indent = " ".repeat(indentation),
    )
}

fn render_helpers(source: &mut String, usage: &Usage) {
    if usage.encode_u32 {
        source.push_str(
            "\nfunction encodeU32(value, name) {\n\
         \x20 if (!Number.isInteger(value) || value < 0 || value > 0xffffffff) {\n\
         \x20   throw new TypeError(`${name} must be an unsigned 32-bit integer`);\n\
         \x20 }\n\
         \x20 return value >>> 0;\n\
         }\n",
        );
    }
    if usage.encode_i32 {
        source.push_str(
            "\nfunction encodeI32(value, name) {\n\
         \x20 if (!Number.isInteger(value) || value < -0x80000000 || value > 0x7fffffff) {\n\
         \x20   throw new TypeError(`${name} must be a signed 32-bit integer`);\n\
         \x20 }\n\
         \x20 return value | 0;\n\
         }\n",
        );
    }
    if usage.encode_f64 {
        source.push_str(
            "\nfunction encodeF64(value, name) {\n\
         \x20 if (typeof value !== \"number\") throw new TypeError(`${name} must be a number`);\n\
         \x20 return value;\n\
         }\n",
        );
    }
    if usage.encode_boolean {
        source.push_str(
            "\nfunction encodeBoolean(value, name) {\n\
         \x20 if (typeof value !== \"boolean\") throw new TypeError(`${name} must be a boolean`);\n\
         \x20 return value ? 1 : 0;\n\
         }\n",
        );
    }
    if usage.encode_enum {
        source.push_str(
            "\nfunction encodeEnum(value, values, name) {\n\
         \x20 const index = values.indexOf(value);\n\
         \x20 if (index === -1) throw new TypeError(`${name} must be one of: ${values.join(\", \")}`);\n\
         \x20 return index;\n\
         }\n",
        );
    }
    if usage.decode_enum {
        source.push_str(
            "\nfunction decodeEnum(value, values, name) {\n\
         \x20 if (value >= values.length) {\n\
         \x20   throw new RangeError(`WebAssembly bridge returned an invalid ${name}`);\n\
         \x20 }\n\
         \x20 return values[value];\n\
         }\n",
        );
    }
}

fn js_string(value: &str) -> String {
    serde_json::to_string(value).unwrap()
}

fn lower_camel(value: &str) -> String {
    let mut characters = value.chars();
    let Some(first) = characters.next() else {
        return String::new();
    };
    first.to_lowercase().chain(characters).collect()
}

fn lower_words(value: &str) -> String {
    let mut result = String::new();
    for (index, character) in value.chars().enumerate() {
        if index != 0 && character.is_uppercase() {
            result.push(' ');
        }
        result.extend(character.to_lowercase());
    }
    result
}
