use std::{fs, path::Path};

use anyhow::Result;

pub(super) fn write_entries(directory: &Path, name: &str, version: &str) -> Result<()> {
    let runtime = quote(&format!("./{name}.runtime.mjs"));
    let wasm = quote(&format!("./{name}.wasm"));
    let bridge = quote(&format!("./{name}.bridge.mjs"));
    let version = quote(version);
    for (environment, source) in [
        (
            "node",
            format!(
                r#"// Generated by bridge_cli. Do not edit.
import {{ readFileSync }} from "node:fs";

import {{ initializeSync }} from {runtime};

initializeSync(readFileSync(new URL({wasm}, import.meta.url)));

export * from {bridge};

export const version = {version};

export default function init() {{
  return Promise.resolve();
}}
"#
            ),
        ),
        (
            "browser",
            format!(
                r#"// Generated by bridge_cli. Do not edit.
import {{ initializeAsync }} from {runtime};

export * from {bridge};

export const version = {version};

export default function init() {{
  return initializeAsync(() =>
    fetch(new URL({wasm}, import.meta.url)).then(instantiate)
  ).then(() => {{}});
}}

async function instantiate(source) {{
  const fallback = source.clone();
  if (typeof WebAssembly.instantiateStreaming === "function") {{
    try {{
      const result = await WebAssembly.instantiateStreaming(source);
      return result.instance;
    }} catch (error) {{
      if (source.ok && source.headers.get("Content-Type") !== "application/wasm") {{
        const result = await WebAssembly.instantiate(await fallback.arrayBuffer());
        return result.instance;
      }}
      throw error;
    }}
  }}
  const result = await WebAssembly.instantiate(await source.arrayBuffer());
  return result.instance;
}}
"#
            ),
        ),
        (
            "module",
            format!(
                r#"// Generated by bridge_cli. Do not edit.
import * as wasm from {wasm};

import {{ initializeSync }} from {runtime};

initializeSync(wasm);

export * from {bridge};

export const version = {version};

export default function init() {{
  return Promise.resolve();
}}
"#
            ),
        ),
    ] {
        let output = directory.join(format!("{name}.{environment}.mjs"));
        fs::write(&output, source)?;
    }
    Ok(())
}

fn quote(value: &str) -> String {
    serde_json::to_string(value).unwrap()
}
