/// Selects how ECMAScript modules are emitted.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct ModulesOptions {
    /// Defaults to [`ModuleType::Preserve`].
    pub r#type: ModuleType,
}

/// Module formats supported by the SWC module passes.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub enum ModuleType {
    #[default]
    Preserve,
    Amd,
    Umd,
    SystemJs,
    CommonJs,
}

/// SWC: <https://github.com/swc-project/swc/blob/3ad7952d41f6ee568ce1e7084a44e2b6aafa3752/crates/swc/src/config/mod.rs#L764>.
pub(crate) fn finish(
    ast: &mut Ast<'_>,
    ctx: &mut TraverseCtx<'_>,
    format: ModuleType,
    filename: Option<&str>,
    features: ModuleFeatures,
) {
    let lower = format != ModuleType::Preserve && ast.is_module();
    if lower && format != ModuleType::SystemJs {
        import_analysis::import_analyzer(ast, ctx, format);
    }
    ctx.helpers.inject_helpers(ast, ctx.resolver);
    if !lower {
        return;
    }

    top_level_this::top_level_this(ast);
    let mut cx = util::ModuleCtx {
        ast,
        resolver: ctx.resolver,
        helpers: &mut ctx.helpers,
        features,
    };
    match format {
        ModuleType::CommonJs => common_js::common_js(&mut cx),
        ModuleType::Amd => amd::amd(&mut cx),
        ModuleType::Umd => umd::umd(&mut cx, filename),
        ModuleType::SystemJs => system_js::system_js(&mut cx),
        ModuleType::Preserve => unreachable!(),
    }
}

/// Syntax available to generated module wrappers and imports.
///
/// Temporary workaround to avoid emitting unsupported syntax after syntax lowering.
/// Remove once syntax lowering covers code generated by module passes.
#[derive(Default, Clone, Copy, Debug, PartialEq, Eq)]
pub struct ModuleFeatures {
    /// Emit `const` for generated module bindings.
    pub block_scoping: bool,
    /// Emit arrows for generated dynamic import callbacks.
    pub arrow: bool,
}
