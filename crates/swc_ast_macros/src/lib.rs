use proc_macro::TokenStream;
use syn::{Ident, Item, Token, parse_macro_input, punctuated::Punctuated};

mod ast;

/// Declares a node or node union in the flat AST schema consumed by `ast_tools`.
///
/// Structs and enums become typed node handles. `repr` marks an enum used as a
/// representation union; `nested` requires `repr`. Field storage types and
/// `#[estree(...)]` metadata are read from the source by the generator.
///
/// # Field invalidation
///
/// Use `#[ast(invalidates(...))]` on a stored field when changing it makes
/// optional metadata stale:
///
/// ```text
/// #[ast]
/// pub struct NumericLiteral {
///     #[ast(invalidates(raw))]
///     value: f64,
///     raw: Option<AstUtf8>,
/// }
/// ```
///
/// The generated setter clears the named fields only when the stored value
/// changes. Compact-bit comparison distinguishes `0.0` from `-0.0`. Builders
/// and cloning initialize fields together and do not trigger invalidation.
/// Targets must be optional fields on the same struct; unknown or duplicate
/// targets, self-invalidation, and dependency cycles are rejected.
#[proc_macro_attribute]
pub fn ast(args: TokenStream, input: TokenStream) -> TokenStream {
    let args = parse_macro_input!(args with Punctuated::<Ident, Token![,]>::parse_terminated);
    let input = parse_macro_input!(input as Item);
    let expanded = ast::expand_ast(
        args.iter().any(|arg| arg == "repr"),
        args.iter().any(|arg| arg == "nested"),
        input,
    );
    TokenStream::from(expanded)
}

/// Describes the public ESTree declarations generated by `ast_tools`.
///
/// Use alongside [`macro@ast`] on nodes and unions, or on an ordinary scalar
/// enum to generate a union of string literals. On scalar enums this macro
/// preserves the Rust enum and removes variant metadata before compilation.
///
/// # Default declarations
///
/// AST structs generate interfaces extending `BaseNode`, which contains UTF-16
/// `start` and `end` offsets. Each interface has a `type` discriminator. Stored
/// field names become camelCase, `SubRange<T>` becomes `Array<T>`, and
/// `Option<T>` becomes `T | null`. Type-name prefixes use `TS`, `JSX`, and `JS`.
/// AST enums generate unions of public variant types. Scalar enum variants
/// become string literals; Rust discriminants do not affect the declarations.
///
/// # Attributes
///
/// | Attribute | Meaning |
/// | --- | --- |
/// | `rename = "..."` | On a struct, sets its `type` discriminator while retaining its interface name. On an enum, renames its declaration and references. On a field, renames the public property. On a unit variant, sets its string literal; on a payload variant, selects a public type reference. |
/// | `ts_type = "..."` | Overrides a field or variant's TypeScript type; on a struct, overrides the discriminator type. |
/// | `skip` | Omits a stored field from declarations. |
/// | `optional` | Allows a field to be absent, independently of whether its value may be `null`. |
/// | `ts_alias = "..."` | Replaces a generated interface or union with a type alias. |
/// | `fields(name(ts_type = "..."))` | Adds a public property absent from Rust storage. Each property requires `ts_type` and may also specify `optional`. |
/// | `add_ts_def = "..."` | Adds exported declarations beside the owning type. |
///
/// Overrides do not change Rust storage or codec behavior. The legacy
/// `skip = "reason"` field form additionally preserves its codec skip behavior;
/// bare `skip` affects declarations only. Duplicate projected fields, including
/// collisions with `BaseNode` properties, are rejected.
///
/// # Examples
///
/// Scalar enums can rename their public values without changing Rust variants:
///
/// ```
/// use swc_next_ast_macros::estree;
///
/// #[estree]
/// pub enum ImportPhase {
///     #[estree(rename = "source")]
///     Source,
///     #[estree(rename = "defer")]
///     Defer,
/// }
/// ```
///
/// For AST declarations, describe computed public properties beside the node:
///
/// ```text
/// #[ast]
/// #[estree(
///     rename = "Literal",
///     fields(value(ts_type = "bigint | null"), bigint(ts_type = "string"))
/// )]
/// pub struct BigIntLiteral {
///     raw: AstUtf8,
/// }
/// ```
///
/// This generates `interface BigIntLiteral` with `type: "Literal"`. On an
/// enum, `#[estree(rename = "Statement")]` instead renames the generated union
/// and references to it. Use `ts_type` when a discriminator needs a union
/// rather than a single string literal.
///
/// Public declarations must cover decoder output and remain encodable into
/// the corresponding Rust AST types. Cross-field grammar constraints are not
/// inferred, and compatibility with other parsers' declarations is not guaranteed.
#[proc_macro_attribute]
pub fn estree(_args: TokenStream, input: TokenStream) -> TokenStream {
    let mut input = parse_macro_input!(input as Item);
    if let Item::Enum(enumeration) = &mut input {
        for variant in &mut enumeration.variants {
            variant.attrs.retain(|attr| !attr.path().is_ident("estree"));
        }
    }
    quote::quote!(#input).into()
}
