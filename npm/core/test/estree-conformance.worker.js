import fs from "node:fs";
import path from "node:path";
import { readExpected } from "./conformance-utils.js";

import { langFromPath, parseSync } from "../src-js/index.js";

// =========================== Paths ==============================
const ROOT_DIR = path.resolve(import.meta.dirname, "../../..");
const FIXTURE_DIR = path.resolve(ROOT_DIR, "tasks/testsuite/fixtures");
const TEST_HARNESS = path.resolve(FIXTURE_DIR, "estree-conformance/src");
const FIELD_ORDERS_FILE = path.resolve(TEST_HARNESS, "field-orders.json");

// ========================= Runner =============================
const { makeUnitsFromTest } = await import(
  path.resolve(TEST_HARNESS, "utils/typescript-make-units-from-test.ts")
);
const { stringifyWith, transformerAcorn } = await import(
  path.resolve(TEST_HARNESS, "utils/json.ts")
);

export default async function runCase({ oracle, source, file }) {
  const oracleFile = path.resolve(oracle, file);
  const sourceFile = (function (source, file) {
    switch (path.extname(file)) {
      case ".json":
        return path.resolve(source, file.slice(0, -".json".length) + ".js");
      case ".md":
        return path.resolve(source, file.slice(0, -".md".length));
      default:
        throw new Error(`Unsupported oracle file: ${file}`);
    }
  })(source, file);

  try {
    const expectedUnits = readExpected(oracleFile).map((expected) => ({
      ...expected,
      astValue: JSON.parse(expected.ast),
    }));

    let sourceCode = fs.readFileSync(sourceFile, "utf8");
    if (sourceCode.charCodeAt(0) === 0xfeff) sourceCode = sourceCode.slice(1);

    const sourceUnits =
      path.extname(oracleFile) === ".md"
        ? makeUnitsFromTest(sourceFile, sourceCode).tests
        : [
            {
              content: sourceCode,
              name: sourceFile,
              sourceType: { jsx: false },
            },
          ];
    const actualAsts = sourceUnits.map((sourceUnit, index) => {
      const expected = expectedUnits[index];
      const { program: ast } = parseSync(sourceUnit.content, {
        comments: "none",
        lang: getLang(sourceUnit, oracleFile),
        // TypeScript ESTree oracles are generated by typescript-eslint, which
        // does not expose parenthesized expression or type wrapper nodes.
        preserveParens: path.extname(oracleFile) !== ".md",
        sourceType:
          expected?.astValue.sourceType ??
          (sourceUnit.sourceType.module ? "module" : "script"),
      });
      return stringifyWith(ast, reorderAstFields);
    });
    const passed =
      actualAsts.length === expectedUnits.length &&
      actualAsts.every((ast, index) => ast === expectedUnits[index].ast);

    return {
      file: sourceFile,
      parsed: true,
      passed,
    };
  } catch (error) {
    return {
      error: error instanceof Error ? error.message : String(error),
      file: sourceFile,
      parsed: false,
      passed: false,
    };
  }
}

// ========================= Adapters =============================
const fieldOrders = JSON.parse(fs.readFileSync(FIELD_ORDERS_FILE, "utf8"));

function getLang(sourceUnit, oracleFile) {
  let lang = langFromPath(sourceUnit.name);
  // TypeScript oracles are produced by typescript-eslint even when a test's
  // virtual `@filename` has a JavaScript extension. Preserve declaration-file
  // mode, but otherwise parse every TypeScript test unit with TS semantics.
  if (path.extname(oracleFile) === ".md" && lang !== "dts") lang = "ts";
  if (!sourceUnit.sourceType.jsx) return lang;
  if (lang === "ts" || lang === "dts") return "tsx";
  if (lang === "js") return "jsx";
  return lang;
}

function reorderAstFields(key, value) {
  if (typeof value === "bigint") return null;
  // JSON.stringify serializes Infinity as null. Use the oracle's placeholder
  // so stringifyWith can emit the numeric JSON token 1e+400 instead.
  if (value === Infinity) return transformerAcorn(key, value);

  if (
    typeof value !== "object" ||
    value === null ||
    !Object.hasOwn(value, "type")
  ) {
    return value;
  }

  const keys = fieldOrders[value.type];
  // TSParameterProperty is missing from the upstream field-order table.
  // Match typescript-eslint's serialized order only for oracle comparison.
  if (!keys && value.type === "TSParameterProperty") {
    return {
      type: value.type,
      accessibility: value.accessibility,
      decorators: value.decorators,
      override: value.override,
      parameter: value.parameter,
      readonly: value.readonly,
      static: value.static,
      start: value.start,
      end: value.end,
    };
  }
  if (!keys) return value;

  const reordered = { type: value.type };
  for (const key of keys) {
    if (Object.hasOwn(value, key)) reordered[key] = value[key];
  }
  for (const key of Object.keys(value)) {
    if (
      key === "type" ||
      key === "start" ||
      key === "end" ||
      keys.includes(key)
    )
      continue;
    reordered[key] = value[key];
  }
  if (Object.hasOwn(value, "start")) reordered.start = value.start;
  if (Object.hasOwn(value, "end")) reordered.end = value.end;

  // RegExp instances are not representable in JSON. Match the serialized
  // Acorn and typescript-eslint oracles without changing parseSync's AST.
  if (
    value.type === "Literal" &&
    Object.hasOwn(value, "regex") &&
    value.regex &&
    typeof value.regex === "object" &&
    typeof value.regex.flags === "string" &&
    Object.hasOwn(reordered, "value")
  ) {
    reordered.value = null;
  }

  return reordered;
}
