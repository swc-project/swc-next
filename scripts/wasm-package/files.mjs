import { readFileSync } from "node:fs";

const GENERATED_HEADER = "// Generated by scripts/wasm-package. Do not edit.\n";
const runtimeSource = readFileSync(
  new URL("../../tasks/bridge_codegen/templates/runtime.mjs", import.meta.url),
  "utf8",
);

export function bindingFileNames(binaryName) {
  return {
    wasm: `${binaryName}.wasm`,
    bridge: `${binaryName}.bridge.mjs`,
    node: `${binaryName}.node.mjs`,
    browser: `${binaryName}.browser.mjs`,
    module: `${binaryName}.module.mjs`,
    runtime: `${binaryName}.runtime.mjs`,
  };
}

export function environmentFiles(names, version) {
  return new Map([
    [names.node, nodeEntry(names, version)],
    [names.browser, browserEntry(names, version)],
    [names.module, moduleEntry(names, version)],
    [names.runtime, runtimeSource],
  ]);
}

function nodeEntry(names, version) {
  return `${GENERATED_HEADER}import { readFileSync } from "node:fs";

import { initializeSync } from ${relative(names.runtime)};

initializeSync(readFileSync(new URL(${relative(names.wasm)}, import.meta.url)));

export * from ${relative(names.bridge)};

export const version = ${JSON.stringify(version)};

export default function init() {
  return Promise.resolve();
}
`;
}

function browserEntry(names, version) {
  return `${GENERATED_HEADER}import { initializeAsync } from ${relative(names.runtime)};

export * from ${relative(names.bridge)};

export const version = ${JSON.stringify(version)};

export default function init() {
  return initializeAsync(() =>
    fetch(new URL(${relative(names.wasm)}, import.meta.url)).then(instantiate)
  ).then(() => {});
}

async function instantiate(source) {
  const fallback = source.clone();
  if (typeof WebAssembly.instantiateStreaming === "function") {
    try {
      const result = await WebAssembly.instantiateStreaming(source);
      return result.instance;
    } catch (error) {
      if (source.ok && source.headers.get("Content-Type") !== "application/wasm") {
        const result = await WebAssembly.instantiate(await fallback.arrayBuffer());
        return result.instance;
      }
      throw error;
    }
  }
  const result = await WebAssembly.instantiate(await source.arrayBuffer());
  return result.instance;
}
`;
}

function moduleEntry(names, version) {
  return `${GENERATED_HEADER}import * as wasm from ${relative(names.wasm)};

import { initializeSync } from ${relative(names.runtime)};

initializeSync(wasm);

export * from ${relative(names.bridge)};

export const version = ${JSON.stringify(version)};

export default function init() {
  return Promise.resolve();
}
`;
}

function relative(file) {
  return JSON.stringify(`./${file}`);
}
