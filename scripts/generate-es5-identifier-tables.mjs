// Run from a directory that can resolve is-es5-identifier-name@1.1.0.
// Pass --check to verify the checked-in tables without writing them.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const args = process.argv.slice(2);
const check = args.length === 1 && args[0] === "--check";
if (args.length !== 0 && !check) {
  throw new Error("Expected no arguments or --check.");
}

const require = createRequire(resolve("package.json"));
const legacyModule = require.resolve("is-es5-identifier-name");
const { version } = JSON.parse(
  readFileSync(join(dirname(legacyModule), "package.json"), "utf8"),
);
if (version !== "1.1.0") {
  throw new Error(`Expected is-es5-identifier-name 1.1.0, found ${version}.`);
}
const { default: isEs5IdentifierName } = await import(
  pathToFileURL(legacyModule).href
);

const workspace = fileURLToPath(new URL("../", import.meta.url));
const lexerFlags = execFileSync(
  "cargo",
  [
    "run",
    "--quiet",
    "--locked",
    "-p",
    "swc_next_formatter_js",
    "--example",
    "identifier_character_flags",
  ],
  { cwd: workspace, stdio: ["ignore", "pipe", "inherit"] },
);
if (lexerFlags.length !== 0x10000) {
  throw new Error("Expected one lexer membership byte per BMP code point.");
}

const identifierStart = 1;
const identifierContinue = 2;
const excludedContinue = [];
const excludedStartOnly = [];

function appendCodePoint(boundaries, point) {
  if (boundaries.at(-1) === point) {
    boundaries[boundaries.length - 1] = point + 1;
  } else {
    boundaries.push(point, point + 1);
  }
}

for (let point = 0x80; point < lexerFlags.length; point++) {
  const flags = lexerFlags[point];
  const character = String.fromCharCode(point);
  if (flags & identifierContinue && !isEs5IdentifierName(`a${character}`)) {
    appendCodePoint(excludedContinue, point);
  } else if (flags & identifierStart && !isEs5IdentifierName(character)) {
    appendCodePoint(excludedStartOnly, point);
  }
}

function renderTable(name, boundaries) {
  const rows = [];
  for (let start = 0; start < boundaries.length; start += 12) {
    const row = boundaries
      .slice(start, start + 12)
      .map((point) => `0x${point.toString(16).padStart(4, "0")},`)
      .join(" ");
    rows.push(`    ${row}`);
  }
  return `#[rustfmt::skip]\npub(super) const ${name}: &[u16] = &[\n${rows.join("\n")}\n];\n`;
}

const output = join(
  workspace,
  "crates/swc_formatter_js/src/formatter/es5_identifier_tables.rs",
);
const generated =
  "//! Generated by scripts/generate-es5-identifier-tables.mjs.\n" +
  "//! Ranges use exclusive upper bounds. See THIRD_PARTY_NOTICES.\n\n" +
  renderTable("EXCLUDED_CONTINUE", excludedContinue) +
  "\n" +
  renderTable("EXCLUDED_START_ONLY", excludedStartOnly);

if (check) {
  if (readFileSync(output, "utf8") !== generated) {
    throw new Error("Regenerate the ES5 identifier exclusions.");
  }
} else {
  writeFileSync(output, generated);
}
